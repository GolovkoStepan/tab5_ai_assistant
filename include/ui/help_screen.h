#pragma once

// Экран помощи и меню переходов (Ctrl+M).
//
// Зачем отдельный экран. Подсказки в нижней полосе чата выросли до двух колонок,
// которые перестали помещаться в 1280 px: правая строка наезжала на левую и
// уходила за край. Сокращать до «C+O — док.» не хотелось — тогда про разделы
// знал бы только автор кода. Поэтому все команды собраны здесь, а внизу чата
// осталась одна короткая строка «Ctrl+M — меню».
//
// Здесь же живут переходы в другие разделы: треды, документы, настройки API,
// Wi-Fi и диагностика. Это и есть меню: команды не надо помнить, их видно.
//
// Экран НЕ переключает себя сам: он выставляет запрос (take_target), а переход
// делает main — как у экрана списка тредов. Иначе экран помощи знал бы про все
// остальные экраны, и получилась бы взаимная зависимость.
//
// Выбор стрелками есть только у пунктов-переходов (левая колонка). Правая —
// справочник: там команды текущих экранов, нажимать их отсюда нечего.

#include <stddef.h>
#include <stdint.h>

#include "hw/keyboard.h"

namespace ui {

class HelpScreen {
public:
    /// Куда просят перейти. None — никуда.
    enum class Target : uint8_t {
        None,
        Threads,
        Notes,
        ApiSettings,
        Wifi,
        Diagnostic,
        About,
    };

    /// Связей с хранилищами у экрана нет — только чтобы вызывающий код
    /// выглядел единообразно с другими экранами.
    void init() {}

    /// Открыть экран: выбор в начало списка.
    void onEnter();

    /// Обработать событие клавиатуры.
    /// @return true, если экран нужно закрыть (Esc)
    bool onKey(const hw::KeyEvent& ev);

    /// Обработать касание: тап выбирает пункт, повторный тап — открывает.
    /// @return true, если касание относилось к меню
    bool onTouch(int x, int y);

    /// Периодическая работа не нужна: содержимое статично.
    void tick() {}

    /// Перерисовать помеченное изменившимся.
    void draw();

    /// Есть ли что перерисовывать. Смена выбора — тоже работа: она рисует две
    /// строки, а не весь экран.
    bool dirty() const { return _redraw_all || _drawn_selected != _selected; }

    /// Забрать запрос на переход (сбрасывает его).
    Target take_target();

private:
    void draw_rows();
    void draw_selection();

    /// Номер выбранного пункта-перехода (0 — первый).
    int _selected{0};
    /// Что реально нарисовано выбранным. Стирать подсветку надо здесь, а не на
    /// номере, который был до нажатия: между кадрами могло пройти несколько
    /// нажатий.
    int _drawn_selected{-1};

    Target _target{Target::None};
    bool _redraw_all{true};
};

}  // namespace ui
