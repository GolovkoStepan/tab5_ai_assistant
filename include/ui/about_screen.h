#pragma once

// Экран «О программе».
//
// Зачем он нужен. Вопросы «та ли прошивка?», «какой сейчас пояс?», «сколько ещё
// памяти свободно?» раньше решались только через Serial: версия — командой
// `version`, модель и адрес API — чтением config.json с компьютера, память —
// логом загрузки. На устройстве, которое берут в руки без ноутбука, это тупик.
//
// Экран ничего не настраивает: настройки живут в своих экранах (Ctrl+A, Ctrl+W).
// Здесь только чтение — поэтому и переходов отсюда нет, кроме выхода.
//
// Данные приносит main: у экрана нет ни доступа к настройкам, ни к драйверам,
// иначе он потянул бы за собой половину прошивки. Снимок обновляется раз в
// секунду: время работы меняется, остальное — почти никогда.

#include <stddef.h>
#include <stdint.h>

#include "hw/keyboard.h"

namespace ui {

class AboutScreen {
public:
    /// Что показать. Строки уже готовы — экран их только раскладывает.
    ///
    /// Копия, а не указатели: main собирает снимок в локальном буфере, и экран
    /// не должен зависеть от того, сколько тот живёт.
    struct Info {
        char version[24]{};
        char model[72]{};
        char api_url[200]{};
        char timezone[40]{};
        /// Местные дата и время; пусто, если время ещё не выставлено.
        char local_time[40]{};
        char uptime[32]{};
        char heap[40]{};
        char psram[40]{};
        char sd_card[40]{};
        char keyboard[40]{};
        char wifi[80]{};
    };

    /// Обновить снимок. Вызывает main раз в секунду.
    ///
    /// Ничего не помечает, если снимок совпал с нарисованным: иначе строки
    /// перерисовывались бы каждую секунду, а на панели TAB5 это заметное
    /// мерцание.
    void set_info(const Info& info);

    const Info& info() const { return _info; }

    /// Открыть экран: полная перерисовка.
    void onEnter();

    /// Обработать событие клавиатуры.
    /// @return true, если экран нужно закрыть
    bool onKey(const hw::KeyEvent& ev);

    /// Касание обрабатывается только как «назад»: на экране нет кнопок.
    /// @return true, если касание закрыло экран
    bool onTouch(int x, int y);

    /// Периодическая работа не нужна: снимок приносит main.
    void tick() {}

    /// Перерисовать помеченное изменившимся (построчно).
    void draw();

    /// Есть ли что перерисовывать.
    bool dirty() const;

private:
    Info _info;
    /// Нарисованный снимок: по нему видно, какие строки изменились.
    Info _drawn;
    bool _drawn_valid{false};
    bool _redraw_all{true};
};

}  // namespace ui
