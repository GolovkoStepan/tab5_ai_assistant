#pragma once

// Системный трей в правом верхнем углу: часы, Wi-Fi и батарея.
//
// Порядок справа налево: дата с часами, палочки Wi-Fi с подписью, затем
// батарея с подписью. Время стоит у самого края — там его ищут глазами, как в
// macOS и на телефоне; значки состояния сдвинуты левее.
//
// Зачем он вообще. До него состояние сети было видно только в чате, а заряд —
// на диагностическом экране: чтобы понять «есть ли связь» или «не разрядился ли
// прибор», надо было уйти с того экрана, где работаешь. Как в macOS, трей
// показывает главное всегда.
//
// **Иконки рисуются примитивами, а не символами.** В efontJA_16 нет блочных
// глифов: U+2581..U+2588 (▁▄█), U+2591 (░), U+25AA (▪) и U+26A1 (⚡) в нём
// отсутствуют — проверено разбором таблицы глифов (scripts/font_probe.py).
// Отсутствующий символ M5GFX рисует рамкой-«квадратом», как было с эмодзи.
// Поэтому палочки Wi-Fi и корпус батареи — `fillRect`, и только текст рядом
// берётся из шрифта.
//
// **Ничего не решает.** Что показывать — правила в util/tray_state (они
// тестируются на хосте). Здесь только геометрия и цвета.

#include <stdint.h>

#include "util/tray_state.h"

namespace ui {

/// Высота полосы трея. 44 px: шапки экранов начинают контент на 48 (чат), 52
/// (заметки), 62 (API), 74 (Wi-Fi) — полоса влезает везде, ничего не сдвигая.
constexpr int kTrayH = 44;

/// Отступ от правого края.
constexpr int kTrayMargin = 16;

/// Область трея в координатах экрана: [x, x+w) × [0, kTrayH).
///
/// Нужна и рисованию, и main: тап проверяется по ней, поэтому границы должны
/// считаться в одном месте, а не повторяться числом.
struct Rect {
    int x{0};
    int y{0};
    int w{0};
    int h{0};

    bool contains(int px, int py) const { return px >= x && px < x + w && py >= y && py < y + h; }
};

/// Область иконки Wi-Fi (для тапа).
Rect wifi_rect(int screen_w);

/// Область иконки батареи (для тапа).
Rect battery_rect(int screen_w);

/// Левая граница трея: правее неё экран не должен рисовать ничего.
///
/// Экраны прижимают к правому краю свои подписи (`открыт: <slug>`, путь к
/// документу). Теперь там живёт трей, поэтому правый край для них — эта
/// граница, а не `width - margin`.
int tray_left_edge(int screen_w);

/// Текущий снимок состояния.
///
/// Глобальный, а не параметр каждого экрана: шапку рисуют шесть разных
/// классов, и передавать снимок через шесть сигнатур значило бы шесть мест,
/// где его можно забыть обновить. Цикл один, поток один — гонок нет.
const tray::Info& live_info();

/// Обновить снимок. Вызывает main раз в секунду, до отрисовки.
void set_live_info(const tray::Info& info);

/// Нарисовать трей целиком.
///
/// Фон закрашивается: трей перерисовывается только при изменении снимка, и
/// старые цифры не должны просвечивать под новыми.
void draw_tray(const tray::Info& info, int screen_w);

/// Нарисовать по текущему снимку. Это вызывают шапки экранов.
void draw_tray(int screen_w);

/// Стереть полосу трея (при полной перерисовке экрана).
void clear_tray(int screen_w);

}  // namespace ui
