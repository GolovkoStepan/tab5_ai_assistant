#pragma once

// Заставка на время запуска.
//
// Зачем она нужна. До неё при включении экран оставался чёрным, пока шла
// инициализация, — а она занимает несколько секунд: M5.begin(), SD-карта,
// настройки, клавиатура на отдельной шине, Wi-Fi через сопроцессор. Всё это
// время устройство выглядело выключенным, и палец тянулся нажать кнопку ещё
// раз. Заставка говорит «я жив, работаю» и показывает, на каком шаге стою.
//
// Почему не «красивая картинка на две секунды». Пауза ради паузы замедляет
// запуск и ничего не сообщает; здесь же каждый показанный шаг — это реально
// выполняемая работа, а задержка нулевая: экран обновляется между шагами
// инициализации. Если инициализация ускорится, заставка просто мелькнёт.
//
// Рисуется примитивами и шрифтом. В efontJA_16 нет блочных глифов, поэтому
// полоса прогресса — `fillRect`, а не `█`; в efontJA_24 (крупный заголовок)
// тоже нет `✓`, поэтому готовность показывается цветом и прочерком.
//
// Ничего не решает и не зависит от остального кода: `begin`/`step`/`finish`
// двигают только отрисовку. Что и в каком порядке инициализировать, по-прежнему
// решает setup().

#include <stdint.h>

namespace ui {

/// Сколько шагов запуска показывает заставка.
///
/// Число фиксировано, а не «сколько вызовет setup()»: полоса прогресса должна
/// быть видна сразу целиком, иначе она прыгает по мере появления шагов.
constexpr int kSplashSteps = 6;

/// Шаги запуска в том порядке, в каком их проходит setup().
enum class SplashStep : uint8_t {
    Display = 0,   ///< дисплей, поворот, яркость
    Storage = 1,   ///< SD-карта
    Settings = 2,  ///< настройки из config.json
    Keyboard = 3,  ///< клавиатура A164
    Network = 4,   ///< Wi-Fi (запускается в фоне, ждать не надо)
    Ready = 5,     ///< всё готово, сейчас откроется меню
};

/// Нарисовать заставку и открыть первый шаг.
///
/// Вызывается сразу после того, как дисплей настроен (до него рисовать некуда).
/// Размеры — `int`, а не `uint8_t`: экран 1280×720 в байт не влезает, и
/// случайное сужение типа обнуляет ширину — заголовок и полоса тогда рисуются
/// от левого края (проверено на плате: была именно эта ошибка).
void splash_begin(int screen_w, int screen_h);

/// Отметить шаг выполненным.
///
/// Рисует строку с галочкой-прочерком и заполняет полосу прогресса. Вызывается
/// из setup() после каждого этапа — то есть заставка показывает настоящий ход
/// инициализации, а не выдуманный таймер.
void splash_step(SplashStep step, const char* note = nullptr);

/// Показать финальную строку и дать ей прочитаться.
///
/// Завершает прогресс и держит кадр `hold_ms`. Смысл паузы только в том, чтобы
/// человек успел увидеть «готово»: без неё экран сменился бы через миллисекунды
/// и выглядел бы как мигание. Значение подобрано так, чтобы не раздражать при
/// частых перезагрузках.
void splash_finish(uint32_t hold_ms = 600);

}  // namespace ui
