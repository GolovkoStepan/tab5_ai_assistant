#pragma once

// Экран архива документов: список, поиск, просмотр, правка, удаление.
//
// Зачем этот экран, если агент уже умеет читать и писать заметки по просьбе.
// Потому что архив хочется просмотреть глазами: «что я там сохранил про
// очиститель?» — вопрос, на который модель ответит, только если догадается
// поискать. А исправить опечатку в сохранённой заметке иначе можно лишь с
// компьютера, тогда как карманный помощник затем и нужен, чтобы его не
// доставать.
//
// Экран работает через `docapi::Store` и про SD напрямую не знает. Вся
// арифметика, которую легко испортить молча, вынесена в чистые модули с
// тестами на хосте:
//   * `textedit`   — вставка, удаление, каретка, отмена;
//   * `textlayout` — строки сетки и связь «каретка ↔ строка/столбец».
// Здесь остаются только файловые вызовы, состояния экрана и отрисовка.
//
// Редактор — построчный, во весь экран, без разметки: markdown-заметка
// правится как обычный текст. Подсветку синтаксиса и перенос по словам
// сознательно не делаем — нужен предсказуемый ввод, а не красивый вид, и
// каретке нужно однозначное соответствие «символ → строка/столбец».
//
// Экран НЕ переключает себя сам: `onKey` возвращает true, когда пора вернуться
// в чат, а сменой экрана занимается main (как у ThreadsScreen).

#include <stddef.h>
#include <stdint.h>

#include "hw/doc_store.h"
#include "hw/keyboard.h"
#include "hw/settings_store.h"
#include "util/doc_api.h"
#include "util/doc_path.h"
#include "util/front_matter.h"
#include "util/text_edit.h"

namespace ui {

class NotesScreen {
public:
    /// Максимальная длина документа, которую правим. Та же, что у DocStore:
    /// больше всё равно не прочитать и не записать атомарно.
    static constexpr size_t kMaxDocBytes = hw::DocStore::kMaxDocBytes;

    /// Сколько документов показываем в списке за раз.
    static constexpr size_t kMaxListedDocs = docapi::kMaxListedDocs;

    /// Предел строк раскладки текста. Документ в 64 КБ кириллицы при ~90
    /// символах в строке даёт около 400 строк; 1024 — запас втрое.
    static constexpr size_t kMaxRows = 1024;

    /// Длина поискового запроса.
    static constexpr size_t kMaxQuery = 96;

    /// Привязать к хранилищам. Вызывается один раз в setup().
    void init(hw::DocStore& docs, hw::SettingsStore& settings);

    /// Открыть экран: перечитать список с карты.
    void onEnter();

    /// Забыть несохранённые правки. Вызывается main при уходе с экрана.
    ///
    /// Правки теряются молча, и это осознанно: диалог при каждом уходе был бы
    /// навязчив, а «не сохранено» видно в строке состояния. Подтверждение есть
    /// только на Esc внутри редактора — там сюрприза быть не должно.
    void onExit();

    /// Обработать событие клавиатуры.
    /// @return true, если экран нужно закрыть
    bool onKey(const hw::KeyEvent& ev);

    /// Обработать касание: выбор строки, повторный тап — открыть.
    /// @return true, если открытие запрошено (экран сделал это сам)
    bool onTouch(int x, int y);

    /// Периодическая работа не нужна: список статичен, редактор тоже.
    void tick() {}

    /// Перерисовать помеченное изменившимся.
    void draw();

    /// Есть ли что перерисовывать.
    bool dirty() const;

    /// Есть несохранённые правки. Нужно main: уход по Ctrl+T во время правки
    /// потерял бы текст, поэтому основная глобальная команда так не работает.
    bool has_unsaved_edits() const { return _dirty; }

    /// Сохранить несохранённую правку перед выключением, без вопросов.
    ///
    /// Отдельно от save_edit(): тот вызывается по Ctrl+S и при выходе из
    /// правки, а при аварийном выключении экран может быть в любом состоянии,
    /// и спрашивать подтверждение уже некогда. Если сохранять нечего — молча
    /// ничего не делает.
    void flush_pending_save();

    /// Показать сообщение в нижней полосе. Нужно main, чтобы объяснить, почему
    /// глобальная команда не сработала.
    void notice(const char* text);

private:
    /// Что делает экран.
    enum class Mode : uint8_t {
        List,     ///< список документов
        Search,   ///< ввод поискового запроса
        View,     ///< просмотр документа без правки
        Edit,     ///< редактор
        Confirm,  ///< подтверждение удаления или выхода с потерей правок
    };

    /// Что подтверждаем.
    enum class ConfirmKind : uint8_t {
        None,
        Delete,
        DiscardEdits,
    };

    // --- Список ---
    void reload();
    void clamp_scroll();
    void open_selected();
    /// Открыть документ по пути и загрузить его в редактор.
    bool open_doc(const char* rel);
    /// Выполнить поиск по введённому запросу.
    void run_search();

    // --- Редактор ---
    void begin_edit();
    /// Сохранить правку (Ctrl+S).
    void save_edit();
    /// Выйти из правки: с вопросом, если есть несохранённые изменения.
    void request_leave_edit();

    /// Пересчитать раскладку и подтянуть окно к каретке.
    ///
    /// @param text_changed текст изменился (а не только каретка переехала)
    void after_edit(bool text_changed);

    // --- Отрисовка (каждая функция чистит свою область) ---
    void draw_header();
    void draw_list();
    void draw_row(int row, bool fill_bg);
    void draw_scrollbar();
    /// Нарисовать окно текста. without caret — просмотр.
    void draw_text(bool with_caret);
    /// Нарисовать каретку на текущем месте и стереть её со старого.
    void draw_caret();
    void draw_status();
    void draw_footer();
    void draw_hints();

    // --- Подтверждения ---
    void resolve_confirm(bool confirmed);
    void confirm_delete(bool confirmed);

    void fail(const char* text);

    hw::DocStore* _docs{nullptr};
    hw::SettingsStore* _settings{nullptr};

    Mode _mode{Mode::List};
    ConfirmKind _confirm{ConfirmKind::None};

    // --- Список ---
    docapi::Entry _items[kMaxListedDocs]{};
    size_t _count{0};
    int _selected{0};
    int _first{0};
    /// Список показывает результаты поиска: Esc возвращает полный список.
    bool _from_search{false};

    /// Документ, который сейчас открыт (путь относительно /notes).
    char _rel[paths::kMaxPathLen]{};
    doc::Meta _meta{};

    // --- Текст документа ---
    /// Тело документа — то, что показывает просмотр и правит редактор.
    char* _text{nullptr};
    textedit::Editor _ed{};

    /// Начала строк раскладки: kMaxRows + 1 смещений (нужен конец последней).
    ///
    /// В PSRAM: 4 КБ на стеке задачи интерфейса — половина её бюджета, а
    /// раскладка пересчитывается на каждый введённый символ.
    uint32_t* _row_offsets{nullptr};

    /// Есть несохранённые правки.
    bool _dirty{false};
    /// Сколько строк в раскладке (для прокрутки и строки состояния).
    int _rows{1};
    /// Первая показанная строка.
    int _scroll{0};
    /// Желаемый столбец каретки при движении вверх/вниз (в символах).
    size_t _desired_col{0};

    /// Поисковый запрос.
    char _query[kMaxQuery]{};

    /// Сообщение в нижней полосе. _notice_ok — подтверждение действия, а не
    /// ошибка: цвет другой.
    char _error[192]{};
    bool _notice_ok{false};

    /// Буфер обрезки строк под ширину экрана (fit_width). Один на экран, а не
    /// на вызов: 192 байта в каждом кадре на стеке задачи интерфейса — заметная
    /// доля её бюджета.
    char _scratch[192]{};

    /// Окно и число документов на момент отрисовки: по ним видно, переехал ли
    /// выбор внутри неподвижного окна.
    int _drawn_first{-1};
    bool _list_valid{false};
    int _drawn_selected{-1};

    /// Экран только что открыли: стереть всё, что показывал прежний.
    bool _need_clear{true};

    bool _redraw_all{true};
    /// Перерисовать всё окно текста, а не отдельные строки.
    bool _redraw_text{false};
    /// Перерисовать только каретку (и стереть прежнюю).
    bool _redraw_caret{false};
    bool _redraw_footer{false};

    /// Положение каретки, нарисованной последней: при движении без правки
    /// перерисовывается только она, а не двадцать четыре строки текста. Правка
    /// окна стоит ~125 мс, а стрелка автоповторяется десятки раз в секунду.
    int _drawn_caret_row{-1};
    int _drawn_caret_col{-1};
};

}  // namespace ui
