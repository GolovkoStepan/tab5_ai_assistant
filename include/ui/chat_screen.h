#pragma once

// Экран чата: лента сообщений, поле ввода, стриминг ответа.
//
// Отдельный класс, а не функции в main: у экрана своё состояние (буфер ввода,
// прокрутка, идёт ли стриминг), и оно живёт дольше одного кадра.
//
// Два правила, выстраданные на этом проекте:
//
//  1. **Никакой полной перерисовки по событию.** Полный кадр — только при входе
//     и при смене режима. Каждая буква ввода трогает только поле ввода,
//     пришедший кусок ответа — только область ленты.
//
//  2. **Стриминг нельзя читать в блокирующем цикле.** Сетевой обмен идёт в
//     tick(): за один вызов забирается только то, что уже пришло. Иначе экран
//     замирал бы на всё время ответа, и Esc не обрабатывался бы.

#include <stdint.h>

#include "hw/api_client.h"
#include "hw/chat_store.h"
#include "hw/doc_store.h"
#include "hw/keyboard.h"
#include "hw/settings_store.h"
#include "hw/wifi.h"
#include "util/chat_view.h"
#include "util/doc_api.h"
#include "util/doc_tools.h"
#include "util/front_matter.h"
#include "util/input_history.h"
#include "util/led_state.h"
#include "util/tool_calls.h"
#include "util/tool_registry.h"
#include "util/web_search.h"
#include "util/web_sources.h"

namespace ui {

class ChatScreen {
public:
    /// Привязать экран к драйверам. Вызывается один раз в setup().
    /// Здесь же выделяется память под растущий ответ и тело запроса: в PSRAM,
    /// потому что ответ на 12 КБ и тело с историей рядом с TLS в внутренней
    /// RAM не поместятся.
    void init(hw::ApiClient& api, hw::ChatStore& store, hw::SettingsStore& settings, hw::WifiManager& wifi,
        hw::DocStore& docs);

    /// Открыть экран: загрузить последний тред или создать новый.
    void onEnter();

    /// Обработать событие клавиатуры.
    /// @return true, если экран нужно закрыть
    bool onKey(const hw::KeyEvent& ev);

    /// Обработать касание. Возвращает true, если касание обработано.
    bool onTouch(int x, int y);

    /// Периодическая работа: продвинуть запрос, обновить индикатор.
    /// **Не рисует** — только выставляет флаги. Вызывать в цикле всегда.
    void tick();

    /// Перерисовать то, что помечено изменившимся.
    void draw();

    /// Есть ли что перерисовывать.
    bool dirty() const;

    /// Прервать запрос (если идёт) и сохранить недописанное при выходе.
    void onExit();

    /// Начать новый тред.
    void new_thread();

    /// Открыть тред по имени (выбор из списка тредов).
    ///
    /// Ответ модели не обрывается: если он идёт, тред не переключается, иначе
    /// недописанный ответ уехал бы в чужой файл. Причина отказа — в _error.
    ///
    /// @return true, если тред открыт
    bool open_thread(const char* slug);

    /// Очистить открытый тред (Ctrl+R).
    ///
    /// Первое нажатие только спрашивает подтверждение вторым, второе — чистит:
    /// тред на карте удаляется безвозвратно, а Ctrl+R стоит рядом с Ctrl+W в
    /// подсказке, так что промах пальцем стоил бы всего разговора.
    void clear_thread(bool confirmed);

    /// Идёт ли запрос к модели.
    bool busy() const { return _mode != Mode::Idle; }

    /// Текст последней ошибки (для экранов, которые вызывают open_thread).
    const char* last_error() const { return _error; }

    /// Распечатать открытый тред в Serial (команда `thread`).
    ///
    /// Нужно для проверки «дошли ли источники до файла»: после прогона тред
    /// читается с карты без единого платного запроса. Public, потому что
    /// вызывает main по команде из Serial.
    void print_thread();

    /// Задать вопрос извне — так, будто его набрали и нажали Enter.
    ///
    /// Нужно команде `ask` по Serial: без неё приёмочный прогон требует
    /// человека у клавиатуры, и повторить его скриптом нельзя. Идёт тем же
    /// путём, что и набранный текст (`send_question`), поэтому проверяются те
    /// же условия: идёт ответ, нет Wi-Fi, нет ключа, вопрос не влез.
    ///
    /// @return false, если вопрос не ушёл; причина — в last_error()
    bool ask(const char* text, size_t len);

    /// Завершить работу перед выключением: прервать запрос и дописать тред.
    ///
    /// Нужно аварийному выключению при разряде. Без него недописанный ответ
    /// модели остался бы только в памяти: файл пишется один раз, когда ответ
    /// дописан (см. hw/chat_store.h), а при выключении посреди стриминга
    /// потерялся бы весь текст — в том числе уже показанный на экране.
    ///
    /// Помечает ответ неполным: «модель сказала столько, сколько успела» — это
    /// правда, а целый ответ после обрыва — нет.
    void shutdown_save();

    /// Показать сообщение, которое ошибкой не является: «тред очищен»,
    /// «введите вопрос», «нужно подтверждение». Текст тот же, но светодиод
    /// не краснеет — иначе подтверждение Ctrl+R выглядело бы как сбой.
    ///
    /// Public, потому что им пользуется аварийное выключение: сообщение о
    /// разряде должно попасть на экран тем же путём, что и остальные
    /// подсказки, а не отдельной строкой.
    void notice(const char* text);

    /// Сохранить последний ответ модели в архив (Ctrl+S, Р-050).
    ///
    /// Нужно, потому что архив раньше наполнялся только тогда, когда модель
    /// догадывалась позвать `write_doc`. Ответ понравился — клавиша, и он в
    /// архиве с блоком «Источники:», если поиск был.
    ///
    /// @return true, если заметка записана
    bool save_answer();

    /// Заполнить «модельную» половину индикации светодиодов клавиатуры.
    ///
    /// Экран знает про режим, повтор и ошибку; половину про питание добавит
    /// вызывающий — у него M5.Power под рукой. Разделение по той же причине,
    /// что и в util/led_state.h: правила цвета проверяются на хосте, а
    /// источники состояния живут там, где эти состояния есть.
    void fill_model_status(led::Status& s) const;

    // --- События стриминга ---------------------------------------------------
    //
    // Вызываются из AnswerSink внутри tick(), то есть в задаче интерфейса —
    // рисовать из них не нужно, они только выставляют флаги. Public, потому
    // что AnswerSink объявлен в анонимном пространстве .cpp, а дружить с ним
    // через friend значило бы завязать заголовок на деталь реализации.

    void on_answer_text(const char* text, size_t len);
    void on_answer_reasoning();
    void on_answer_usage(long input_tokens, long output_tokens);
    void on_answer_finished(const char* reason);
    void on_answer_retry(int attempt, int delay_s);
    void on_answer_error(const char* message);

    /// Модель просит вызвать инструменты. Только копирует набор: выполнять
    /// инструменты в обработчике потока нельзя — цикл агента должен идти в
    /// tick(), иначе Esc не сработает, пока не отработают все шаги.
    void on_tool_calls(const tools::Accumulator& calls);

    /// Источники веб-поиска из ответа (Р-036). Копим за весь ход: за шаг
    /// агента их может прийти несколько наборов, а показать надо все.
    void on_web_sources(const web::List& sources);

    // --- События поискового подзапроса (Р-040) ---------------------------------
    //
    // Поиск идёт отдельным запросом со своим слушателем. Текст поискового
    // ответа уходит в СВОЙ буфер, а не в ленту: открытой реплики ассистента в
    // этот момент нет, и пересказ поисковика не должен попасть в тред — там
    // будет ответ основной модели. Источники при этом идут в общий список хода
    // через on_web_sources(): он один на ход и дедуплицирует по URL.

    /// Кусок текста поискового ответа.
    void on_search_text(const char* text, size_t len);
    void on_search_usage(long input_tokens, long output_tokens);
    void on_search_finished(const char* reason);
    void on_search_error(const char* message);
    void on_search_retry(int attempt, int delay_s);

private:
    /// Что делает экран прямо сейчас.
    enum class Mode : uint8_t {
        Idle,        ///< можно печатать
        Sending,     ///< запрос ушёл, первого текста ещё нет
        Streaming,   ///< идёт текст ответа
        Searching,   ///< выполняется поисковый подзапрос по вызову web_search
        Confirming,  ///< ждём подтверждения удаления файла агентом
    };

    /// Счётчики и состояние идущего ответа.
    ///
    /// Сам текст живёт в ChatStore::_tail, а не здесь: экран и тред не должны
    /// держать две копии одного ответа на 12 КБ. Здесь только то, что нужно
    /// экрану и чего в треде ещё нет, — токены из `usage` и пометка обрыва.
    struct Answer {
        long input_tokens{0};
        long output_tokens{0};
        /// Ответ оборван (Esc, ошибка сети) — сохраняется с пометкой.
        bool partial{false};
    };

    // --- Жизненный цикл ---

    void enter_mode(Mode m);

    /// Показать ошибку. Ошибка — это когда что-то не получилось: нет сети,
    /// сервер ответил отказом, SD не пишется. Такую и красим красным
    /// светодиодом клавиатуры.
    void fail(const char* text);

    /// Сбросить состояние экрана после смены содержимого треда: лента, поле
    /// ввода, прокрутка, измерения.
    void reset_after_thread_change();

    // --- Отправка ---
    /// Отправить введённый вопрос. false — не отправлено, причина в _error.
    bool send_question();
    /// Собрать тело запроса из истории треда в _body.
    size_t build_body();
    /// Завершить ответ: сохранить в тред и вернуть экран в Idle.
    void finish_answer(bool ok, const char* reason);

    // --- Агентский цикл ---
    //
    // Модель может вместо текста попросить инструменты. Тогда ход не
    // заканчивается: сохраняем сообщение ассистента с вызовами, выполняем их,
    // дописываем в тред результаты role=tool и отправляем следующий запрос.
    // До cfg::kMaxAgentSteps шагов, неблокирующе — Esc должен работать всегда.

    /// Разобраться с завершённым ответом: закрыть ход или пойти на следующий шаг.
    /// Вызывается из tick(), а не из обработчика потока: start() нового
    /// запроса внутри on_finished() сбило бы накопитель клиента.
    void handle_turn_end();

    /// Дописать источники веб-поиска отдельной репликой в тред (Р-036).
    ///
    /// Отдельной, а не в текст ответа: ссылки — не слова модели, и при
    /// сохранении заметки `source_url` берётся из них, а не выдумывается.
    /// Реплика живёт в треде, поэтому источники видны и после перезагрузки.
    void append_web_sources();

    /// Выполнить ОДИН шаг агента: следующий вызов или, если вызовы кончились,
    /// отправить запрос с их результатами. Вызывается из tick() — по шагу на
    /// кадр, чтобы Esc работал во время работы с SD.
    ///
    /// @return true — есть ещё работа; false — ход закрыт или ждёт пользователя
    bool step_agent();

    /// Выполнить один вызов и дописать результат в тред.
    void execute_call(const tools::Call& call);

    /// Дописать в тред результат инструмента (role=tool).
    void answer_call(const tools::Call& call, const char* text);

    /// Отправить следующий запрос цикла — с результатами инструментов.
    bool send_agent_turn();

    /// Пользователь ответил на вопрос об удалении.
    void resolve_delete(bool confirmed);

    // --- Веб-поиск (Р-040) ---
    //
    // Поиск — обычный инструмент: модель зовёт `web_search`, прошивка делает
    // ОТДЕЛЬНЫЙ запрос с плагином `web` и возвращает модели найденное.
    // Плагина в основном запросе нет: иначе сервер искал бы по тексту любой
    // реплики, включая «привет», и брал бы за это ~2,1 ₽.

    /// Отправить поисковый подзапрос. false — не удалось начать, причина в
    /// _search_reason.
    bool begin_search(const char* query, uint8_t max_results);

    /// Разобраться с закончившимся поиском: отдать модели результат и
    /// продолжить цикл агента.
    void finish_search();

    // --- Клавиатура ---
    void handle_typing_key(const hw::KeyEvent& ev);
    void backspace();

    /// Шаг по истории ввода: +1 — вверх (старше), -1 — вниз (новее).
    void history_step(int direction);

    // --- Отрисовка (каждая функция чистит свою область) ---
    void draw_all();
    void draw_title();
    void draw_feed();
    void draw_input_field();
    void draw_status();
    void draw_error();
    void draw_hints();

    /// Дописать кусок ответа в тред. Возвращает false, если ответ переполнил
    /// буфер треда — тогда он помечен неполным.
    bool append_answer(const char* text, size_t len);

    /// Вернуть в поле ввода вопрос, оставшийся в треде без ответа.
    ///
    /// Вызывается, когда ответ отменили до первого слова: иначе вопрос висит в
    /// треде без пары, и следующий ответ модели относится к нему. Откат и в
    /// файле, и в памяти делает ChatStore::undo_last_user(); экран только
    /// возвращает текст в поле, чтобы набранное не пропало.
    void restore_unsent_question();

    /// Пересчитать, сколько строк занимает каждое сообщение.
    ///
    /// Инкрементально: пересчитываются только новые сообщения и последнее
    /// (ответ растёт по кускам). Пересчёт всего треда на каждый токен — это
    /// сотни wrap_text на кадр, а лента перерисовывается на каждом событии
    /// стриминга.
    void measure_messages();

    /// Нарисовать ленту, ограничившись полосой [band_top, band_bottom).
    ///
    /// Полоса нужна для прокрутки: там лента не перерисовывается целиком, а
    /// сдвигается уже нарисованное, и дорисовать надо только открывшуюся
    /// полоску. Строки вне полосы пропускаются.
    void paint_feed(const chatview::Window& win, int band_top, int band_bottom);

    /// Нарисовать полосу прокрутки в правом поле ленты.
    ///
    /// Живёт вне области сдвига: иначе copyRect увозил бы её вместе с текстом
    /// и на время кадра она оказывалась бы в двух местах.
    void draw_scrollbar(size_t total, size_t max_lines);

    /// Нарисовать одну строку ленты: залить фон, текст и маркер.
    void paint_row(int y, int feed_w, const char* text, int text_x, uint16_t fg, uint16_t bar_color);

    /// Сдвинуть готовое изображение ленты и дорисовать открывшуюся полосу.
    /// @return false, если сдвиг невозможен и нужна полная перерисовка
    bool shift_feed(size_t total, size_t max_lines);

    /// Запомнить состояние ленты на момент отрисовки.
    void remember_feed(size_t total);

    /// Сбросить результаты измерения: тред сменился.
    void invalidate_measure();

    /// Перемерить только последнее сообщение.
    ///
    /// Нужно, когда у уже измеренного сообщения меняется не текст, а признак
    /// «показывать ли»: ход модели становится служебным, когда к нему
    /// дописываются вызовы инструментов. Длина текста при этом не меняется, и
    /// обычное правило «перемерять по изменению длины» его пропустит.
    void remeasure_last();

    /// Текущее время в ISO-8601 с учётом таймзоны из настроек. Пусто, если
    /// время ещё не выставлено (RTC пуст и NTP не ответил).
    void now_iso(char* out, size_t out_len) const;

    /// Напечатать в Serial то, что легло в заметку (для приёмки по `ask`).
    void log_written_doc();

    /// Напечатать в Serial итог хода: источники, шаги, хвост треда.
    void log_turn_result();

    /// Сколько символов влезает в строку ленты. Измеряется по реальной ширине
    /// глифов: зашитое «94» было бы неверным для латиницы.
    static size_t chars_per_line();
    /// Ширина текста ленты в пикселях.
    static int feed_text_width();

    /// Сколько строк занимает текст при данной ширине строки. 0 — пустой.
    static uint16_t count_lines(const char* text, size_t width);
    /// Разбить текст на строки, вернуть смещения начал.
    static size_t split_lines(const char* text, size_t width, size_t* offsets, size_t max_lines);

    /// Сколько строк занимает лента целиком и сколько помещается на экране.
    /// total_lines() сперва досчитывает кэш — иначе прокрутка на первое
    /// нажатие стрелки видела бы ноль строк.
    size_t total_lines();
    size_t visible_lines() const;

    hw::ApiClient* _api{nullptr};
    hw::ChatStore* _store{nullptr};
    hw::SettingsStore* _settings{nullptr};
    hw::WifiManager* _wifi{nullptr};
    hw::DocStore* _docs{nullptr};

    /// Реестр инструментов архива. Сам реестр маленький (8 описаний), а всё
    /// тяжёлое — буферы ниже, они в PSRAM.
    tools::Registry _tools;

    /// Накопитель, собранный сетью. Копия нужна потому, что ApiClient сбрасывает
    /// свой при завершении запроса, а подтверждение удаления может растянуться
    /// на несколько кадров и ждать пользователя.
    tools::Accumulator* _agent_calls{nullptr};

    /// Сколько шагов агента уже сделано в этом ходе.
    int _agent_step{0};
    /// Какой вызов выполнять следующим (после подтверждения).
    size_t _agent_call_index{0};
    /// Пришёл набор вызовов — обработать в tick().
    bool _have_calls{false};

    /// Агент в работе: в следующем кадре выполнить очередной вызов.
    /// Вызовы идут по одному на кадр — работа с SD, все сразу заморозили бы
    /// экран (см. step_agent()).
    bool _agent_pending{false};

    /// Ответ завершился (успешно или нет) — разобрать в tick().
    ///
    /// Флаг вместо прямого вызова: on_finished() приходит из _api->tick(), и
    /// начинать оттуда новый запрос значило бы переинициализировать парсер под
    /// работающим feed().
    bool _turn_ended{false};
    bool _turn_ok{true};

    /// Причина завершения хода: "stop", "length", "cancel" — или текст ошибки
    /// от сети.
    ///
    /// Размер как у _error: здесь оказывается не только причина, но и
    /// сообщение сервера («Лимит трат по ключу исчерпан: 100,22 из 100,00
    /// руб. …»). Прежние 32 байта резали его посреди кириллицы, и на экране
    /// оставались первые одиннадцать букв — именно это и выглядело
    /// «непонятной ошибкой».
    char _turn_reason[160]{};

    /// Номер вызова, ждущего подтверждения удаления. SIZE_MAX — нет такого.
    size_t _confirm_index{static_cast<size_t>(-1)};
    /// Путь, который агент просит удалить.
    char _confirm_path[paths::kMaxPathLen]{};

    /// JSON-схемы инструментов: собираются один раз в init() и пересобираются
    /// при смене настройки веб-поиска (Р-040: выключенный поиск — это
    /// отсутствующий `web_search` в списке, а не поле в запросе).
    static constexpr size_t kToolsJsonCap = 16 * 1024;
    char* _tools_json{nullptr};
    /// При каком значении `search_enabled` собраны схемы. Смена настройки видна
    /// только по конфигу, а он меняется с экрана Ctrl+A во время сеанса.
    bool _tools_search_on{true};

    /// Тело поискового подзапроса (Р-040). Собирается на каждый поиск: запрос
    /// короткий, но история диалога в него не попадает — это отдельный запрос
    /// с одной парой сообщений.
    static constexpr size_t kSearchBodyCap = 4 * 1024;
    char* _search_body{nullptr};

    /// Сообщение ассистента с вызовами — эхо обратно в API.
    static constexpr size_t kCallsJsonCap = 40 * 1024;
    char* _calls_json{nullptr};

    /// Буфер результата инструмента и буфер тела документа для него.
    char* _tool_out{nullptr};
    char* _tool_body{nullptr};

    /// Источники веб-поиска за текущий ход (Р-036). Не в стеке: восемь
    /// записей по ~600 байт. Живут до конца хода — их показываем в ленте и
    /// отдаём в `source_url` документа.
    web::List* _web_sources{nullptr};
    /// Поиск в этом ходе вообще выполнялся: отличает «ничего не нашлось» от
    /// «поиска не было», чтобы подпись была честной.
    bool _web_search_ran{false};
    /// Поиск закончился неудачей (сеть, отказ сервера, Esc). «Не нашёл» и «не
    /// смог» — разные вещи: показывать второе как первое значило бы врать.
    bool _web_search_failed{false};

    /// Ход ждёт результата поиска: вызов `web_search` уже выполнен, подзапрос
    /// отправлен, результат ещё не вернулся.
    bool _search_pending{false};
    /// Буфер текста поискового подзапроса. Отдельный от ленты: в этот момент
    /// ни открытой реплики ассистента, ни сообщения в треде нет — текст нужен
    /// только как материал для результата инструмента.
    static constexpr size_t kSearchTextCap = 4096;
    char* _search_text{nullptr};
    size_t _search_text_len{0};
    bool _search_ended{false};
    bool _search_ok{true};
    /// Причина неудачи поиска. Своя, а не _turn_reason: ход продолжается, и
    /// портить его причину нельзя.
    char _search_reason[160]{};
    /// Запрос и число результатов для текущего поиска (из аргументов вызова).
    char _search_query[wsearch::kMaxQueryLen + 1]{};
    uint8_t _search_max_results{0};
    /// Сколько источников уже было в общем списке хода к началу ЭТОГО поиска.
    ///
    /// Список один на ход, поэтому по его общему размеру нельзя понять, что
    /// принёс именно этот поиск: второй поиск в том же ходе отчитался бы
    /// ссылками первого. В результат идут только источники после этой отметки.
    size_t _search_src_from{0};
    /// Поиск в статусе: строка «ищу в сети: запрос…».
    char _search_status[96]{};
    /// Токены поискового подзапроса: они тоже потрачены и должны попасть в
    /// счётчики сессии, иначе сумма за сессию врёт.
    long _search_input_tokens{0};
    long _search_output_tokens{0};

    /// Списки и результаты поиска для инструментов: 15 КБ и 3 КБ — только в
    /// PSRAM, на стеке задачи цикла их нет.
    docapi::Entry* _doc_entries{nullptr};
    docapi::Hit* _doc_hits{nullptr};

    /// Контекст вызова инструмента: заполняется на каждый вызов, чтобы
    /// обработчики не искали буферы сами.
    tools::Context _tool_ctx;

    /// Фильтр внутренней разметки DSML в тексте ответа (Р-025).
    tools::DsmlFilter _dsml;
    /// Буфер под отфильтрованный кусок: выход не длиннее входа.
    char _dsml_buf[4096]{};

    Mode _mode{Mode::Idle};

    /// Ответ переполнил буфер треда, и запрос надо прервать: отмена делается в
    /// tick(), потому что из обработчика потока уничтожать парсер нельзя.
    bool _abort_overflow{false};

    /// Буфер ввода. Вопрос редко длиннее пары экранов.
    static constexpr size_t kInputCap = 2048;
    char _input[kInputCap]{};
    size_t _input_len{0};

    /// История введённых вопросов (Alt+↑ / Alt+↓). Арена — в PSRAM: двадцать
    /// слотов по 2 КБ плюс черновик, 42 КБ во внутренней RAM не найти.
    inputhist::History _hist{};
    char* _hist_arena{nullptr};

    Answer _answer;

    /// Тело запроса: история легко даёт десятки килобайт.
    char* _body{nullptr};
    static constexpr size_t kBodyCap = 128 * 1024;

    /// Сообщение о последнем действии: ошибка или пояснение.
    char _error[160]{};

    /// Последнее действие не получилось (а не просто «вот что случилось»).
    /// Отдельный флаг, а не разбор текста: по строке «тред очищен» и «тред не
    /// открылся» отличить успех от сбоя нельзя.
    bool _failed{false};

    /// Прокрутка ленты в строках от конца (0 — самый низ).
    size_t _scroll{0};

    /// Сколько строк занимает каждое сообщение.
    uint16_t* _line_counts{nullptr};

    /// Сумма по _line_counts. Кэш, чтобы прокрутка не пересчитывала тред.
    size_t _total_lines{0};

    /// Для скольких сообщений _line_counts уже посчитан. Отдельно от
    /// _store->count(): последнее сообщение растёт, и его надо пересчитывать.
    size_t _measured_count{0};

    /// Длина последнего измеренного сообщения. По её изменению видно, что
    /// растущий ответ надо перемерить: режим экрана для этого не годится —
    /// быстрый ответ приходит целиком за один тик, и к первому кадру экран уже
    /// снова Idle.
    size_t _measured_last_len{0};

    /// Прокрутка, при которой лента была нарисована, и сколько строк в ней было
    /// тогда. По ним видно, можно ли обойтись сдвигом изображения вместо
    /// полной перерисовки.
    size_t _drawn_scroll{0};
    size_t _drawn_total{0};
    /// Лента нарисована полностью и её можно сдвигать. Сбрасывается сменой
    /// треда, размером окна и полной перерисовкой.
    bool _feed_valid{false};

    /// Токены за сессию: сумма по всем ответам с момента включения.
    long _session_input{0};
    long _session_output{0};

    /// Время ожидания ответа — для индикатора «думаю» с точками.
    unsigned long _wait_started{0};
    /// Сколько точек уже нарисовано (0..3): перерисовываем только при смене.
    int _dots{-1};
    /// Последний показанный счётчик секунд ожидания.
    int _wait_sec{-1};

    /// Сервер попросил подождать: номер попытки и пауза в секундах. 0 — не
    /// ждём. Пока ждём, статус говорит «повтор через N с», а не «думаю»:
    /// иначе пауза в полминуты выглядела бы как зависание.
    int _retry_attempt{0};
    int _retry_delay_s{0};
    unsigned long _retry_started_ms{0};
    /// Последняя показанная секунда обратного отсчёта: по её смене видно, что
    /// строку статуса пора перерисовать.
    int _retry_left_s{-1};

    /// Ctrl+R нажат один раз: ждём подтверждения. Сбрасывается любым другим
    /// действием — иначе подтверждение «залипло» бы, и через минуту случайное
    /// Ctrl+R стерло бы тред без вопроса.
    bool _clear_armed{false};

    /// Состояние Wi-Fi в прошлом кадре. Строка, а не флаг: заголовок
    /// перерисовывается и при смене адреса, а не только факта подключения.
    char _net_cache[64]{};

    // Флаги перерисовки.
    bool _redraw_all{true};
    bool _redraw_title{false};
    bool _redraw_feed{false};
    bool _redraw_input{false};
    bool _redraw_status{false};
    bool _redraw_error{false};
};

}  // namespace ui
