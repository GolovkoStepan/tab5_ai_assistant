#pragma once

// Правила предупреждения о разряде и аварийного выключения.
//
// Зачем отдельный модуль. Порогов три (20 %, 10 %, 5 %), и каждое правило
// легко испортить незаметно:
//
//   * предупреждение должно появляться ОДИН раз при переходе через порог, а не
//     каждую секунду — иначе баннер мигает и заслоняет экран;
//   * предупреждение снимается, когда воткнули кабель: «садится» при зарядке —
//     прямая ложь, а процент на Tab5 при заряде вообще недостоверен
//     (docs/DECISIONS.md Р-016);
//   * при неизвестном проценте не предупреждаем вовсе: на пустом отсеке
//     getBatteryLevel() отдаёт 100 %, а при снятии батареи — мусор;
//   * «аварийно» наступает только ниже последнего порога и только на разряде.
//
// Модуль чистый: ни Arduino, ни M5GFX. Что делать по уровню (показать строку,
// сберечь тред, выключиться через PMS150G) решает main.

#include <stdint.h>

namespace power {

/// Пороги в процентах. Значения по умолчанию — из app_config.h, но здесь они
/// параметром: настройки лежат в config.json и могут отличаться.
struct Thresholds {
    uint8_t warn{20};
    uint8_t critical{10};
    uint8_t shutdown{5};
};

/// Насколько серьёзна ситуация с питанием.
enum class Level : uint8_t {
    /// Всё в порядке либо процент неизвестен.
    Ok,
    /// Пора предупредить: заряд ниже порога `warn`.
    Warn,
    /// Критично: заряд ниже `critical`, пора сохранять и искать розетку.
    Critical,
    /// Заряд ниже `shutdown`: выключаться, пока не потеряли данные.
    Shutdown,
};

/// Уровень по текущему заряду.
///
/// @param known    процент достоверен (только на разряде, см. tray::Charge)
/// @param percent  0..100
/// @return Ok при неизвестном проценте: выдуманное «садится» хуже молчания
Level level(bool known, int percent, const Thresholds& t);

/// Что показывать дальше, зная, что показывали раньше.
///
/// Отдельно от level(), потому что предупреждение — событие, а не состояние:
/// при уровне Warn оно должно появиться один раз, а при возврате к Ok —
/// сняться. Без этой памяти баннер перерисовывался бы каждую секунду.
///
/// @param shown  что показывалось в прошлый раз
/// @param now    текущий уровень
/// @return что показывать; переход Ok → Warn и обратно — единственные
///         изменения, остальное сохраняется
Level next_shown(Level shown, Level now);

/// Текст предупреждения для баннера в чате.
///
/// Пустая строка для Level::Ok. Числа в тексте нет намеренно: процент
/// недостоверен на заряде, а на разряде он и так виден в трее, — важнее
/// действие («подключите зарядку»), а не цифра.
const char* message(Level level);

}  // namespace power
