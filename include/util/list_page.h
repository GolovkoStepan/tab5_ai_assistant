#pragma once

// Арифметика страниц списков: «показано 60 из 137».
//
// Зачем отдельный модуль. Список документов и список тредов читаются с карты
// порциями (`docapi::kMaxListedDocs` = 60, `ChatStore::kMaxListedThreads` = 40),
// и до v1.1.0 лишнее отбрасывалось МОЛЧА: человек видел «Документы: 60» и не
// знал, что в архиве их 137. Хуже — он не знал, что дальше есть ещё, и делал
// вывод «моей заметки тут нет».
//
// Правила вынесены в чистые функции, потому что ошибка здесь не косметическая:
// неверный `has_more` прячет весь остаток архива, а неверный `page_start`
// показывает те же строки дважды.
//
// Модуль чистый: ни Arduino, ни M5GFX.

#include <stddef.h>

namespace listpage {

/// Сколько записей уже показано, начиная со смещения.
///
/// @param total  сколько всего нашлось
/// @param offset с какой записи начата страница
/// @param loaded сколько записей реально прочитано (может быть меньше остатка)
size_t shown(size_t total, size_t offset, size_t loaded);

/// Есть ли ещё записи после показанной страницы.
bool has_more(size_t total, size_t offset, size_t loaded);

/// С какой записи начинать следующую страницу.
///
/// Не `offset + loaded`, а минимум из этого и `total`: если файлы удалили между
/// чтениями, сумма ушла бы за конец, и следующая страница оказалась бы пустой.
size_t next_offset(size_t total, size_t offset, size_t loaded);

/// Подпись списка: «Документы: 60 из 137».
///
/// Если всё поместилось, число одно — «Документы: 12»: «12 из 12» занимало бы
/// место ради повторения одного и того же.
///
/// @param noun   «Документы», «Треды», «Найдено»
/// @param total  сколько всего
/// @param shown  сколько показано
/// @param out    буфер
/// @param out_len его размер
/// @return длина записанного без нуля
size_t label(const char* noun, size_t total, size_t shown, char* out, size_t out_len);

/// Подсказка о продолжении: «→ — ещё 77».
///
/// Отдельно от подписи: подпись стоит в заголовке, подсказка — внизу, и
/// повторять в ней «60 из 137» значило бы занимать строку тем же числом.
///
/// @param remaining сколько осталось
/// @return длина записанного без нуля; 0 — остатка нет, подсказку не рисуем
size_t more_hint(size_t remaining, char* out, size_t out_len);

}  // namespace listpage
