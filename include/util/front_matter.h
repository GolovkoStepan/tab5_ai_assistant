#pragma once

// YAML-фронтматтер документа: разбор и сборка.
//
// Формат описан в docs/ARCHITECTURE.md §5.1:
//
//   ---
//   title: Сброс ошибки очистителя
//   tags: [бытовая-техника, очиститель]
//   source_url: https://example.com/purifier
//   created: 2026-11-23T20:31:00+03:00
//   updated: 2026-11-23T20:31:00+03:00
//   ---
//
// Зачем свой разбор, а не YAML-библиотека: нужен крошечный подмножество
// (плоские пары ключ-значение плюс список тегов в квадратных скобках), а
// полноценный YAML-парсер с зависимостью и аллокациями на 4 КБ документа
// дороже, чем 150 строк кода. Риск ошибки снижен тестами: фронтматтер ломается
// молча — документ просто перестаёт открываться на компьютере.
//
// Важное требование: файл должен читаться обычным markdown-редактором и на
// компьютере. Поэтому пишем ровно тот формат, который описан, а не «как
// получится».

#include <stddef.h>
#include <stdint.h>

namespace doc {

/// Разобранный фронтматтер.
///
/// Строки копируются: фронтматтер маленький (сотни байт), а указатели в
/// чужой буфер жили бы не дольше вызова.
struct Meta {
    char title[128]{};
    /// Теги через запятую, как в исходнике: `бытовая-техника, очиститель`.
    ///
    /// Запятая — разделитель, внутри одного тега её быть не может: иначе
    /// «собрать → разобрать» терял бы границу тега. Формат хранения простой
    /// (одна строка вместо массива), а поиск по тегам идёт подстрокой.
    char tags[128]{};
    char source_url[160]{};
    /// ISO-8601 со смещением: `2026-11-23T20:31:00+03:00`. Пусто — не записано.
    char created[32]{};
    char updated[32]{};

    bool operator==(const Meta& o) const;
    bool operator!=(const Meta& o) const { return !(*this == o); }

    bool has_title() const { return title[0] != '\0'; }
};

/// Разобрать документ: отделить фронтматтер от тела.
///
/// @param text      весь файл
/// @param len       его длина
/// @param out       куда положить поля
/// @param body_out  указатель на начало тела внутри text (или nullptr, если не нужен)
/// @param body_len  длина тела
/// @return false, если фронтматтера нет или он не закрыт. Документ без
///         фронтматтера документом не считается (ARCHITECTURE.md §5.1), но
///         читать его всё равно надо — поэтому тело возвращается и при false.
bool parse(const char* text, size_t len, Meta& out, const char** body_out = nullptr, size_t* body_len = nullptr);

/// Собрать документ целиком: фронтматтер + тело.
///
/// @param meta   поля; пустые пропускаются (кроме title — он обязателен)
/// @param body   текст документа
/// @param out    буфер
/// @param out_len его размер
/// @return длина или 0, если не влезло
size_t build(const Meta& meta, const char* body, char* out, size_t out_len);

/// Экранировать значение для YAML: строка в кавычках, если в ней есть
/// символы, ломающие разбор (`:`, `#`, начало с пробела и т. п.).
///
/// @return длина записанного или 0, если не влезло
size_t escape_value(const char* value, char* out, size_t out_len);

}  // namespace doc
