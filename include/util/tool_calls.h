#pragma once

// Разбор того, что модель вернула про инструменты.
//
// Здесь две вещи, обе выяснены живым прогоном (см. Р-025 в DECISIONS.md):
//
//  1. **Накопитель вызовов.** В стриминге аргументы приходят кусками: короткий
//     вызов `read_doc` приехал за 12 чанков, в каждом лежит `index` и огрызок
//     JSON. Склеивать обязательно — иначе на выходе обрывок вроде `{"path": "ho`.
//     Плюс модель умеет просить несколько инструментов за один ход, поэтому
//     накопитель держит массив, а не один вызов.
//
//  2. **Фильтр DSML.** Если в запросе не передать `tools`, модель иногда
//     печатает свою внутреннюю разметку `<｜｜DSML｜｜ calls>` прямо в текст
//     ответа. Воспроизводилось в 1 прогоне из 3 — то есть вылезет и у
//     пользователя. Мы всегда передаём `tools`, но это страховка: поведение
//     недетерминированное, и один чистый прогон ничего не доказывает.
//
// Чистые функции без Arduino (ArduinoJson есть и в env:native), поэтому
// проверяются на хосте: ошибиться в склейке чанков глазами невозможно.

#include <stddef.h>
#include <stdint.h>

namespace tools {

/// Сколько вызовов за один ход держим. Восемь — как лимит шагов агента:
/// больше всё равно не выполнить, а память не бесконечна.
constexpr size_t kMaxCallsPerTurn = 8;

/// Пределы полей. Идентификатор и имя короткие по природе; аргументы —
/// это JSON с текстом документа, но write_doc с большим текстом придёт
/// отдельным инструментом, а не через аргументы.
constexpr size_t kMaxIdLen = 64;
constexpr size_t kMaxNameLen = 32;
/// 4 КБ, а не 2: русская буква в UTF-8 занимает два байта, и заметка на
/// 1.5 тысячи символов уже не влезала бы. Восемь таких вызовов — 34 КБ, это
/// PSRAM, а не стек.
constexpr size_t kMaxArgsLen = 4096;

/// Один вызов инструмента, собранный из дельт.
struct Call {
    /// Индекс вызова в этом ходе (поле `index` из дельты).
    int index{0};
    /// Идентификатор вызова. Сервер его не сверяет (проверено: принял
    /// заведомо неверный `tool_call_id`), поэтому проверять соответствие
    /// «вопрос — ответ» придётся нам.
    char id[kMaxIdLen]{};
    /// Размер синтетического идентификатора (`call_3`) для вызовов без id.
    static constexpr size_t kFallbackIdLen = 16;
    char name[kMaxNameLen]{};
    /// Аргументы как JSON-текст. Разбирать только целиком: до конца потока
    /// это может быть обрывок.
    char arguments[kMaxArgsLen]{};
    size_t arguments_len{0};
};

/// Накопитель вызовов одного хода.
///
/// Использование: reset() в начале ответа, feed() на каждый чанк, потом
/// обход count()/at(). После обработки — reset() перед следующим ходом.
class Accumulator {
public:
    void reset();

    /// Добавить вызовы из чанка SSE (или из полного ответа без стриминга).
    ///
    /// Понимает обе формы: `choices[0].delta.tool_calls` (поток) и
    /// `choices[0].message.tool_calls` (сервер проигнорировал stream:true).
    ///
    /// @return false, если JSON не разобрался — чанк пропускается, поток
    ///         продолжается: незнакомый чанк не повод рвать ответ
    bool feed(const char* json, size_t len);

    bool any() const { return _count > 0; }
    size_t count() const { return _count; }
    const Call& at(size_t i) const { return _calls[i]; }

    /// Текст последней ошибки сборки: переполнение поля или потерянный вызов.
    /// Пустая строка — всё в порядке. Не фатально: вызывающий решает, вернуть
    /// ли это модели как ошибку инструмента.
    const char* error() const { return _error; }

    /// Свободная память, занятая накопителем. Для диагностики на плате:
    /// 8 вызовов по 2 КБ аргументов — это 16 КБ, такое должно жить в PSRAM.
    static constexpr size_t kBytes = kMaxCallsPerTurn * sizeof(Call);

private:
    /// Приписать текст к полю с учётом предела. true — если не влезло.
    static bool appendTo(char* dst, size_t cap, size_t& len, const char* src, size_t src_len);

    /// Найти или создать слот для вызова с данным индексом.
    Call* slotFor(int index);
    void setError(const char* text);

    Call _calls[kMaxCallsPerTurn]{};
    size_t _count{0};
    char _error[96]{};
};

/// Идентификатор вызова для отправки. У вызова без id (сервер не прислал)
/// подставляется синтетический `call_<index>`: сообщение role=tool обязано на
/// что-то ссылаться. Подстановка должна быть ОДНА на весь код — иначе
/// сообщение ассистента и ответ инструмента сошлются на разные id.
void effective_id(const Call& call, char* out, size_t out_len);

/// Собрать массив вызовов в виде, который кладётся в сообщение ассистента и
/// уходит обратно в API: `[{"id":…,"type":"function","function":{…}}, …]`.
///
/// Нужно, чтобы вернуть модели её же вызовы вместе с результатами. Без этого
/// сообщения сервер не понимает, на что отвечают сообщения role=tool.
/// Аргументы переносятся как текст: разбирать и собирать заново значило бы
/// получить не то, что сказала модель.
///
/// @return длина массива без нуля; 0, если буфер мал
size_t build_calls_json(const Accumulator& calls, char* out, size_t out_len);

// --- Фильтр DSML ------------------------------------------------------------

/// Отсекает внутреннюю разметку DSML из текста ответа.
///
/// Правило простое: как только в тексте встретился маркер `<｜｜DSML｜｜`,
/// всё дальнейшее не показываем. До маркера текст законный («Инструмент вернул
/// пустой ответ — попробую ещё раз»), после — машинная разметка, которой в
/// чате делать нечего.
///
/// Маркер может разъехаться по границе чанков (он 13 байт, а дельты бывают по
/// 2–3 символа), поэтому фильтр держит хвост, который ещё может оказаться
/// началом маркера, и ничего не отдаёт, пока не убедится.
class DsmlFilter {
public:
    void reset();

    /// Прогнать кусок текста.
    ///
    /// @param out     буфер вывода; должен вмещать не меньше len байт
    ///                (выход никогда не длиннее входа — мы только выбрасываем)
    /// @return сколько байт записано в out
    size_t feed(const char* in, size_t len, char* out, size_t out_cap);

    /// Поток закончился: отдать удержанный хвост, если это не маркер.
    /// Без вызова в конце потерялись бы последние 1–12 байт ответа.
    size_t flush(char* out, size_t out_cap);

    /// Маркер найден — текст дальше отброшен. По этому признаку видно, что
    /// модель пыталась «вызвать» инструмент разметкой, а не через tool_calls.
    bool triggered() const { return _triggered; }

    /// Длина маркера в байтах (для тестов и диагностики).
    static size_t markerLen();

private:
    /// Удержанный хвост: байты, совпавшие с началом маркера.
    char _pending[16]{};
    size_t _pending_len{0};
    bool _triggered{false};
};

}  // namespace tools
