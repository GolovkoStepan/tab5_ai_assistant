#pragma once

// Разбор потока Server-Sent Events (SSE).
//
// RouterAI отдаёт стриминг ответа модели в формате SSE: строки `data: {...}`,
// между событиями — пустая строка, в конце — `data: [DONE]`. Формат простой, но
// разбирать его «по строкам из Serial» нельзя: TCP приносит произвольные куски,
// и граница чанка регулярно попадает в середину строки или даже в середину
// UTF-8 символа. Здесь байты складываются в буфер, а события выдаются только
// целиком.
//
// Почему отдельный модуль, а не разбор в ApiClient: это чистая логика, её можно
// прогнать на хосте тестами, не поднимая ни платы, ни сети. Все известные баги
// стриминга (потерянное событие на границе буфера, зависание на пустой строке)
// ловятся здесь за миллисекунды.

#include <stddef.h>

namespace sse {

/// Максимальный размер одного события. Чанк ответа модели — это несколько
/// токенов, то есть десятки байт. 8 КБ — с большим запасом; всё, что больше,
/// скорее свидетельствует о мусоре в потоке, чем о полезных данных.
constexpr size_t kMaxEventBytes = 8192;

/// Максимальная длина одной строки потока (без учёта `\n`).
constexpr size_t kMaxLineBytes = 4096;

/// Получатель одного готового события: полезная нагрузка после `data:`.
/// Буфер действителен только на время вызова.
/// @param data полезная нагрузка события (не завершена нулём)
/// @param len  длина нагрузки в байтах
/// @param ctx  произвольный контекст вызывающего
using EventHandler = void (*)(const char* data, size_t len, void* ctx);

class Parser {
public:
    Parser(EventHandler handler, void* ctx) : _handler(handler), _ctx(ctx) {}

    /// Скормить очередной кусок потока.
    ///
    /// @return false, если поток завершён (`data: [DONE]`) — дальше читать
    ///         бессмысленно, соединение можно закрывать
    bool feed(const char* data, size_t len);

    /// Вернуть парсер в начальное состояние.
    void reset();

    /// Поток завершён маркером `[DONE]`.
    bool done() const { return _done; }

    /// Сколько событий выброшено из-за превышения kMaxEventBytes. Ненулевое
    /// значение означает потерю данных: это не «нормальный» случай, а признак
    /// того, что сервер прислал что-то неожиданное.
    unsigned dropped() const { return _dropped; }

private:
    /// Обработать накопленную строку (без завершающего \n).
    void handle_line(const char* line, size_t len);

    /// Выдать накопленное событие обработчику.
    /// @return false, если это был маркер [DONE]
    bool dispatch();

    EventHandler _handler{nullptr};
    void* _ctx{nullptr};

    /// Накопитель события: несколько строк `data:` склеиваются через \n.
    char _event[kMaxEventBytes]{};
    size_t _event_len{0};
    bool _event_overflow{false};
    /// Событие содержало хотя бы одно поле `data:`. Нужно, чтобы отличить
    /// «нет данных» (разделитель, `event:`, `id:`) от `data:` с пустым
    /// значением — последнее по формату SSE является событием.
    bool _has_data{false};

    /// Накопитель текущей строки.
    char _line[kMaxLineBytes]{};
    size_t _line_len{0};
    bool _line_overflow{false};

    bool _done{false};
    unsigned _dropped{0};
};

}  // namespace sse
