#pragma once

// Разбор потока Server-Sent Events (SSE).
//
// RouterAI отдаёт стриминг ответа модели в формате SSE: строки `data: {...}`,
// между событиями — пустая строка, в конце — `data: [DONE]`. Формат простой, но
// разбирать его «по строкам из Serial» нельзя: TCP приносит произвольные куски,
// и граница чанка регулярно попадает в середину строки или даже в середину
// UTF-8 символа. Здесь байты складываются в буфер, а события выдаются только
// целиком.
//
// Почему отдельный модуль, а не разбор в ApiClient: это чистая логика, её можно
// прогнать на хосте тестами, не поднимая ни платы, ни сети. Все известные баги
// стриминга (потерянное событие на границе буфера, зависание на пустой строке)
// ловятся здесь за миллисекунды.

#include <stddef.h>

namespace sse {

/// Максимальный размер одного события (полезная нагрузка после `data:`).
///
/// Обычный чанк ответа — десятки байт. Но событие с источниками веб-поиска
/// (Р-036) приходит **одним куском**: `delta.annotations` с массивом
/// `url_citation`, где у каждого поля `url`, `title` и `content` до 500
/// символов. Замерено на живом API 26.11.2026: 3 источника — 3.4 КБ,
/// 5 — 5.2 КБ, 8 — 7.9 КБ, 10 — 9.8 КБ.
///
/// Поэтому 16 КБ, а не 8: при десяти источниках (предел `web::kMaxSources`)
/// событие занимает ~9.8 КБ, а прежние 8 КБ не вмещали уже и пять — источники
/// терялись молча, потому что событие выбрасывается целиком, а вместе с ним и
/// все ссылки ответа.
constexpr size_t kMaxEventBytes = 16 * 1024;

/// Максимальная длина имени поля SSE (`data`, `event`, `id`, `retry`).
///
/// Отдельного буфера под всю строку больше нет: значение `data:` пишется прямо
/// в накопитель события. Прежний буфер строки в 4 КБ был вторым, более
/// строгим лимитом — событие источников на 5 КБ не влезало в него, хотя в
/// накопитель события помещалось.
constexpr size_t kMaxFieldBytes = 16;

/// Получатель одного готового события: полезная нагрузка после `data:`.
/// Буфер действителен только на время вызова.
/// @param data полезная нагрузка события (не завершена нулём)
/// @param len  длина нагрузки в байтах
/// @param ctx  произвольный контекст вызывающего
using EventHandler = void (*)(const char* data, size_t len, void* ctx);

class Parser {
public:
    Parser(EventHandler handler, void* ctx) : _handler(handler), _ctx(ctx) {}

    /// Скормить очередной кусок потока.
    ///
    /// @return false, если поток завершён (`data: [DONE]`) — дальше читать
    ///         бессмысленно, соединение можно закрывать
    bool feed(const char* data, size_t len);

    /// Вернуть парсер в начальное состояние.
    void reset();

    /// Поток завершён маркером `[DONE]`.
    bool done() const { return _done; }

    /// Сколько событий выброшено из-за превышения kMaxEventBytes. Ненулевое
    /// значение означает потерю данных: это не «нормальный» случай, а признак
    /// того, что сервер прислал что-то неожиданное.
    unsigned dropped() const { return _dropped; }

private:
    /// Завершить текущую строку: пустая строка выдаёт событие.
    void end_line();

    /// Принять один байт внутри строки (без `\n`).
    ///
    /// Значение поля `data:` пишется прямо в накопитель события, а не в
    /// отдельный буфер строки: у события источников (Р-036) одна строка
    /// длиной до 10 КБ, и второй буфер на 4 КБ молча съедал её целиком.
    void put_char(char ch);

    /// Выдать накопленное событие обработчику.
    /// @return false, если это был маркер [DONE]
    bool dispatch();

    EventHandler _handler{nullptr};
    void* _ctx{nullptr};

    /// Накопитель события: несколько строк `data:` склеиваются через \n.
    char _event[kMaxEventBytes]{};
    size_t _event_len{0};
    bool _event_overflow{false};
    /// Событие содержало хотя бы одно поле `data:`. Нужно, чтобы отличить
    /// «нет данных» (разделитель, `event:`, `id:`) от `data:` с пустым
    /// значением — последнее по формату SSE является событием.
    bool _has_data{false};

    /// Имя поля текущей строки: `data`, `event`, `id`, `retry` или что-то ещё.
    /// Отдельного буфера под всю строку нет — только под имя, потому что
    /// значение `data:` сразу уходит в накопитель события.
    char _field[kMaxFieldBytes]{};
    size_t _field_len{0};
    /// Двоеточие после имени поля уже встречено: дальше идёт значение.
    bool _in_value{false};
    /// Пробел сразу после двоеточия — часть разделителя, в данные не входит.
    /// Учитывается только один пробел: второй уже данные (`test_space_after_colon_only_once`).
    bool _skip_space{false};
    /// Текущая строка — `data:`; значит её байты пишутся в накопитель события.
    bool _line_is_data{false};
    /// Имя поля не влезло в `_field` — строка не SSE-поле, значение не нужно.
    bool _skip_field{false};
    /// В текущей строке уже были байты (нужно для правила «\r перед \n»).
    bool _line_has_bytes{false};

    bool _done{false};
    unsigned _dropped{0};
};

}  // namespace sse
