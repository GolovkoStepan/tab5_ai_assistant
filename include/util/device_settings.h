#pragma once

// Параметры устройства, которые раньше правились только в config.json.
//
// Зачем отдельный модуль. На экране «Параметры» (Ctrl+G, Р-049) четыре поля с
// шагом: яркость, таймаут подсветки, раскладка и пороги разряда. Правила у них
// не косметические:
//
//   * яркость ниже 16 делает экран практически чёрным, и найти обратную дорогу
//     к настройке нельзя — это устройство без аппаратной кнопки яркости;
//   * таймаут идёт по «человеческим» ступеням (1, 2, 5, 10, 20, 30 мин), а не
//     по единице: добрать 15 минут стрелкой — это пятнадцать нажатий;
//   * пороги разряда обязаны убывать (warn > critical > shutdown), иначе
//     предупреждение не покажется никогда. Стрелка, которая это ломает, не
//     должна менять число молча;
//   * таймзону в формате POSIX на клавиатуре не набрать, поэтому её выбирают
//     из списка.
//
// Всё это чистые функции: экран только рисует и передаёт шаг. Модуль не знает
// ни про M5GFX, ни про файлы.

#include <stddef.h>
#include <stdint.h>

#include "util/settings.h"

namespace devsettings {

/// Нижняя граница яркости. Ниже — экран почти чёрный, а аппаратной кнопки,
/// чтобы вернуть подсветку, у Tab5 нет.
constexpr uint8_t kBrightnessMin = 16;
constexpr uint8_t kBrightnessMax = 255;
/// Шаг яркости: 15 ступеней на весь диапазон — от «ночью в темноте» до
/// «на солнце». Мельче не нужно, а крупнее заметно на глаз.
constexpr uint8_t kBrightnessStep = 16;

/// Таймаут подсветки, минуты. 0 — не гасить вовсе.
constexpr uint8_t kMinTimeout = 0;
constexpr uint8_t kMaxTimeout = 60;

/// Границы порогов разряда, проценты.
constexpr uint8_t kMinBattery = 1;
constexpr uint8_t kMaxBattery = 60;

/// Один порог разряда.
enum class Battery : uint8_t {
    Warn,      ///< «пора зарядить»
    Critical,  ///< «скоро выключусь»
    Shutdown,  ///< аварийное выключение
};

/// Готовая таймзона: подпись для экрана и строка в формате POSIX.
///
/// Список, а не ввод: POSIX-строку («YEKT-5») на клавиатуре не набрать, а
/// IANA-имя («Asia/Yekaterinburg») newlib на ESP32 не понимает — TZ станет
/// пустой, и все метки уедут в UTC молча (Р-043).
struct Zone {
    const char* name;
    const char* posix;
};

/// Сколько зон в списке.
size_t zone_count();

/// Зона по индексу. nullptr, если индекса нет.
const Zone* zone_at(size_t index);

/// Индекс зоны с такой POSIX-строкой, или -1 — зона не из списка.
int zone_index(const char* posix);

/// Следующая (delta > 0) или предыдущая зона по кругу.
///
/// Круг, а не отказ на краю: зон немного, и «упёрся в конец списка» читалось бы
/// как поломка. Незнакомая строка считается нулевой зоной — так экран всегда
/// показывает что-то осмысленное.
const Zone& zone_step(const char* posix, int delta);

/// Изменить яркость на delta шагов с ограничением границ.
uint8_t brightness_step(uint8_t current, int delta);

/// Изменить таймаут на delta ступеней.
///
/// Ступени: 0, 1, 2, 5, 10, 20, 30, 60. Соседняя ступень — это и есть шаг, а
/// не прибавка к числу: между 1 и 2 минутами разницы нет, а между 2 и 10 —
/// есть.
uint8_t timeout_step(uint8_t current, int delta);

/// Изменить порог разряда на delta процентов, не ломая порядок.
///
/// Порядок `warn > critical > shutdown` обязателен: при обратном уровне
/// «критично» наступит раньше «предупреждения», и предупреждение не покажется
/// никогда (правило в util/settings::validate). Поэтому порог упирается в
/// соседний, а не перескакивает его.
///
/// @param cfg   настройки, которые правятся на месте
/// @param which какой порог
/// @param delta шаг в процентах
/// @return true, если значение изменилось; false — уже упёрлось в соседа или
///         в границу диапазона
bool battery_step(settings::Config& cfg, Battery which, int delta);

/// Значение порога.
uint8_t battery_value(const settings::Config& cfg, Battery which);

/// Подпись порога для экрана.
const char* battery_name(Battery which);

/// Строка параметра для команды `dev` по Serial (Р-046).
enum class Param : uint8_t {
    None,  ///< не распознано
    Brightness,
    Timeout,
    Layout,
    Warn,
    Critical,
    Shutdown,
    Timezone,
    /// `dev save` — сохранить черновик (то же, что Ctrl+S на экране).
    Save,
};

/// Шаг параметра: что менять и на сколько.
struct Step {
    Param param{Param::None};
    /// Направление: +1 — как →, -1 — как ←. У `layout` не используется.
    int delta{0};
};

/// Разобрать `bright+1`, `timeout-1`, `layout`, `tz+1`.
///
/// Нужно, чтобы экран параметров проверялся скриптом: яркость и пороги разряда
/// иначе нажимаются только руками, и прогон не повторяется (Р-046). Разбор —
/// чистая функция, поэтому проверяется на хосте.
///
/// @return шаг; `param == Param::None`, если строка не распознана
Step parse_step(const char* text, size_t len);

}  // namespace devsettings
