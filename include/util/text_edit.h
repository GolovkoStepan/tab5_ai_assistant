#pragma once

// Редактирование текста с кареткой — без Arduino, тесты на хосте.
//
// Зачем отдельный модуль, а не «вставить символ в буфер» прямо в экране.
// Редактор заметок — это десяток операций над ОДНИМ буфером, и почти каждая
// ошибается тихо: курсор уезжает за конец строки, Backspace разрезает
// кириллицу пополам, отмена возвращает текст не на то место. На плате такие
// дефекты ищут по испорченному документу на карте, поэтому вся арифметика
// вынесена в чистые функции и покрыта тестами.
//
// Два правила, из которых следует всё остальное.
//
// 1. **Каретка — байтовое смещение по границе UTF-8.** Внутрь многобайтного
//    символа она не встаёт никогда: иначе Backspace удалял бы половину
//    «ш», на экране появлялся бы ромбик, а в файл уезжал битый UTF-8.
//
// 2. **Отмена хранит не копии текста, а обратные операции.** Заметка на 30 КБ
//    и восемь копий в PSRAM — 240 КБ на то, чтобы вернуть одну букву. Обратная
//    операция занимает десятки байт: «в этом месте стёрто 2 байта „ш“» или
//    «здесь вставлено 1 байт».

#include <stddef.h>
#include <stdint.h>

namespace textedit {

/// Сколько шагов отмены помним. Тридцать два нажатия — это примерно столько,
/// сколько набирают, прежде чем заметить ошибку. Дальше — уже не «опечатка».
constexpr size_t kMaxUndo = 32;

/// Максимальная длина текста одной обратной операции. Одиночный символ — до
/// 4 байт; запас на будущие операции со словом.
constexpr size_t kMaxUndoText = 16;

/// Одна обратная операция.
///
/// kind == Insert: в этой позиции было ВСТАВЛЕНО len байт, отмена — стереть их.
/// kind == Erase:  в этой позиции было СТЁРТО text_len байт, отмена — вернуть.
struct UndoOp {
    enum class Kind : uint8_t {
        Insert,
        Erase,
    };

    Kind kind{Kind::Insert};
    size_t pos{0};
    size_t len{0};
    char text[kMaxUndoText]{};
    size_t text_len{0};
};

/// Буфер и каретка — состояние одного редактируемого документа.
///
/// Буфер выделяет вызывающий: на устройстве это PSRAM, в тестах — массив на
/// стеке. Модуль не выделяет память вообще: внутри tick() куча шевелиться не
/// должна.
struct Editor {
    char* data{nullptr};
    size_t cap{0};
    size_t len{0};
    size_t caret{0};
    UndoOp undo[kMaxUndo];
    size_t undo_count{0};
};

/// Привязать буфер к редактору и загрузить в него текст.
///
/// @return false, если текст не влез — тогда редактор пуст
bool load(Editor& ed, char* buf, size_t cap, const char* text, size_t text_len);

/// Длина символа UTF-8, начинающегося с байта `lead` (1..4).
size_t char_len(unsigned char lead);

/// Смещение начала ПРЕДЫДУЩЕГО символа от pos (0 — уже в начале).
size_t prev_char(const char* s, size_t pos);

/// Смещение СЛЕДУЮЩЕГО символа от pos (len — уже в конце).
size_t next_char(const char* s, size_t pos, size_t len);

/// Поставить каретку в допустимые границы и на границу символа.
void clamp_caret(Editor& ed);

/// Вставить текст в позицию каретки, каретка встаёт после вставленного.
///
/// @return false, если не поместилось (буфер не меняется)
bool insert(Editor& ed, const char* text, size_t text_len);

/// Вставить один символ UTF-8 (то, что приходит с клавиатуры).
bool insert_char(Editor& ed, const char* utf8);

/// Удалить символ перед кареткой.
/// @return false, если удалять нечего
bool backspace(Editor& ed);

/// Удалить символ под кареткой (клавиша Delete).
/// @return false, если каретка в конце
bool delete_forward(Editor& ed);

/// Удалить от каретки до начала строки (Ctrl+Backspace).
bool delete_to_line_start(Editor& ed);

/// Сдвиги каретки на символ.
void move_left(Editor& ed);
void move_right(Editor& ed);

/// Начало строки, в которой стоит каретка (0 — первая строка).
size_t line_start(const Editor& ed);

/// Конец строки (позиция '\n' или len).
size_t line_end(const Editor& ed);

/// Отменить последнюю операцию.
/// @return false, если отменять нечего
bool undo(Editor& ed);

/// Забыть историю отмены (например, после сохранения).
void clear_undo(Editor& ed);

// Вертикального движения здесь СОЗНАТЕЛЬНО нет: в редакторе оно идёт по
// строкам ЭКРАННОЙ СЕТКИ (с переносом по ширине), а не по строкам файла, и
// живёт в util/text_layout (`move_vertical`). Две реализации одного движения с
// разной семантикой — это гарантированные расхождения: стрелка «вниз» в
// редакторе перескакивала бы через строку или уезжала в начало.

/// Сколько шагов отмены записано.
///
/// inline обязателен: функция определена в заголовке и попадает в каждый
/// объектный файл. Без него линковка сборки «исходники + тест» падает на
/// duplicate symbol — и это неочевидная ошибка, пока не попробуешь собрать.
inline size_t undo_depth(const Editor& ed)
{
    return ed.undo_count;
}

}  // namespace textedit
