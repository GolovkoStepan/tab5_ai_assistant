#pragma once

// Какие строки ленты чата видны в окне экрана.
//
// Лента листается снизу вверх: свежие сообщения важнее старых, и при открытии
// треда показывается конец разговора. Логика «сколько строк помещается и откуда
// начинать» нетривиальна — при неверном подсчёте на экране оказывается пустота
// или сообщение обрывается на середине. Поэтому она вынесена в чистую функцию
// и проверяется на хосте.

#include <stddef.h>
#include <stdint.h>

namespace chatview {

/// Служебный ход модели: пустой текст и только вызовы инструментов.
///
/// По протоколу OpenAI такое сообщение обязано остаться в истории: на него
/// ссылаются последующие `role=tool`, и без него сервер не свяжет результаты с
/// вызовами. Но показывать в ленте нечего — подпись «модель» и пустая строка
/// под ней. На живой плате это выглядело как пустые реплики перед каждым
/// вызовом инструмента и после него.
///
/// Правило здесь, а не в экране: его должны одинаково применять измерение
/// строк и отрисовка, иначе окно ленты разъедется с содержимым.
bool service_turn(size_t content_len, size_t tool_calls_len);

/// Сколько строк помещается в области ленты.
///
/// @param area_height высота области в пикселях
/// @param line_height высота одной строки текста
size_t lines_per_page(int area_height, int line_height);

/// Видимое окно ленты.
struct Window {
    /// Индекс первого видимого сообщения. -1, если показывать нечего.
    int first_msg{-1};
    /// Номер первой видимой строки внутри этого сообщения.
    size_t first_line{0};
    /// Сколько сообщений видно (начиная с first_msg).
    size_t visible_count{0};
    /// Сколько строк всего занято видимыми сообщениями.
    size_t lines_used{0};
    /// Сверху что-то осталось за кадром: рисуем многоточие или тень.
    bool clipped_top{false};
    /// Снизу что-то осталось за кадром.
    bool clipped_bottom{false};
};

/// Вычисляет видимое окно.
///
/// Заполняет снизу вверх: последнее сообщение прижато к низу области. Так
/// свежий ответ всегда виден целиком, даже если он один занимает весь экран.
///
/// @param line_counts сколько строк занимает каждое сообщение (может быть 0 —
///                    например, у пустого)
/// @param count       число сообщений
/// @param max_lines   сколько строк помещается на экране (>= 1)
/// @param scroll      на сколько строк прокручено вверх от конца (0 — самый низ)
Window compute(const uint16_t* line_counts, size_t count, size_t max_lines, size_t scroll);

}  // namespace chatview
