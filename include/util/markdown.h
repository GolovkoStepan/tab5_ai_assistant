#pragma once

// Чистка markdown для ленты чата.
//
// Экран рисует текст как есть: M5GFX не понимает разметку. Модель же пишет
// ссылки в виде `[mi.com](https://www.mi.com/…)`, и человек видел скобки,
// адрес целиком и удвоенный текст вместо ссылки (проверено на плате
// 26.11.2026). Запрет в системном промпте — просьба, а не гарантия: модель
// всё равно иногда размечает, поэтому чистим на показе.
//
// Чистим ТОЛЬКО показ. В треде и в истории запроса текст остаётся исходным:
//  - это ответ модели, и переписывать его на карте значило бы терять данные;
//  - модель, увидев своё сообщение искажённым, сбивалась бы с стиля.
//
// Чистые функции без Arduino — проверяются на хосте.

#include <stddef.h>

namespace md {

/// Убрать разметку, которую экран не умеет показать.
///
/// Что делается:
///  - `[текст](адрес)` → `текст` (если текст пуст — остаётся адрес);
///  - `**жирный**`, `__жирный__`, `*курсив*`, `_курсив_` → текст без маркеров;
///  - `` `код` `` → текст без обратных кавычек;
///  - `#` в начале строки → убирается вместе с пробелом (заголовок);
///  - знаки списка `-`, `*`, `+` в начале строки → остаются: они и в обычном
///    тексте читаются как пункт, а их удаление спутало бы пункты с абзацем.
///
/// Многоточие и «…» не трогаются. Переводы строк сохраняются: лента считает
/// строки по ним.
///
/// @param src     исходный текст (может быть nullptr)
/// @param len     длина без нуля; 0 — значит strlen(src)
/// @param out     буфер результата
/// @param out_len размер буфера
/// @return длина результата без нуля (0, если не поместилось целиком —
///         лучше показать пусто, чем обрывок с половиной ссылки)
size_t plain(const char* src, size_t len, char* out, size_t out_len);

/// Нужна ли чистка: есть ли в тексте хоть один маркер разметки.
///
/// Нужна, чтобы не гонять копирование 12 КБ на каждый кадр: у большинства
/// сообщений разметки нет, и их можно рисовать прямо из треда.
bool needed(const char* src, size_t len);

}  // namespace md
