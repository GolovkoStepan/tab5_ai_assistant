#pragma once

// Проверка ключа API перед сохранением в NVS.
//
// Зачем отдельная функция: ключ уходит в HTTP-заголовок `Authorization`, а
// заголовки в HTTP/1.1 передаются в latin-1. Кириллица (легко попадает при
// копировании из чата вместе с пояснением) делает запрос неотправляемым, причём
// ошибка выглядит как «сервер не ответил». Проверить это на хосте дешевле, чем
// ловить на плате.
//
// Чистые функции без Arduino — тестируются в env:native.

#include <stddef.h>

namespace apikey {

/// Проверяет, что строка годится для заголовка Authorization.
///
/// Требования: только ASCII 0x21..0x7E (печатные, без пробелов), длина в
/// пределах [min_len, max_len]. Пробелы и переводы строк запрещены ещё и
/// потому, что перевод строки в заголовке — это инъекция заголовков.
///
/// @param key     строка ключа
/// @param max_len максимально допустимая длина без завершающего нуля
/// @param err     буфер для причины отказа (может быть nullptr)
/// @return true, если ключ можно отправлять
bool validate(const char* key, size_t max_len, char* err, size_t err_len);

/// Убирает обрамляющие пробелы, переводы строк и кавычки: ключ часто копируют
/// из документа вместе с ними.
///
/// Работает на месте. Возвращает длину результата без завершающего нуля.
size_t clean(char* key);

/// Минимальная длина осмысленного ключа. Короткие строки — это скорее
/// случайно вставленный кусок текста, чем ключ.
constexpr size_t kMinLen = 16;

}  // namespace apikey
