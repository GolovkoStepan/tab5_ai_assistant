#pragma once

// Список Wi-Fi сетей и проверка пароля — чистые функции без зависимостей от
// Arduino, чтобы их можно было проверить на хосте.
//
// Зачем отдельно от драйвера: `WiFi.scanNetworks()` на живой плате отдаёт
// список как есть — с дубликатами одной сети (несколько точек доступа,
// репитер), в произвольном порядке и с уже устаревшими уровнями сигнала.
// Всё это надо привести в вид, пригодный для экрана, и именно эту часть
// дешевле держать в чистом коде с тестами.

#include <stddef.h>
#include <stdint.h>

namespace wifi {

/// Сколько сетей показываем. Столько строк влезает на экран без прокрутки
/// (720 px при строке 40 px минус заголовок и подсказки).
constexpr size_t kMaxNetworks = 12;

/// SSID по стандарту — до 32 байт плюс завершающий ноль.
constexpr size_t kMaxSsidLen = 33;

/// Одна сеть в списке.
struct Network {
    char ssid[kMaxSsidLen]{};
    /// Уровень сигнала в dBm: -30 рядом, -90 на пределе.
    int16_t rssi{0};
    /// Сеть требует пароль.
    bool secure{false};
};

/// Список сетей в порядке, готовом к показу.
struct NetworkList {
    Network items[kMaxNetworks]{};
    uint8_t count{0};

    bool empty() const { return count == 0; }
    const Network& operator[](size_t i) const { return items[i]; }
};

/// Очищает список.
void clear(NetworkList& list);

/// Добавляет сеть, если она полезна для экрана.
///
/// Дубликаты по SSID схлопываются: остаётся точка доступа с сильнейшим
/// сигналом. Без этого одна квартира с репитером занимала пол-списка
/// одинаковыми строками, и выбрать «ту самую» сеть было нельзя.
///
/// Пропускаются: пустой SSID (скрытая сеть — подключаться к ней всё равно
/// нечем, имени нет), некорректный уровень сигнала и список, заполненный
/// до kMaxNetworks.
///
/// @return true, если сеть попала в список
bool add(NetworkList& list, const char* ssid, int rssi, bool secure);

/// Сортировка по убыванию сигнала. Устойчивая: при равном уровне сохраняется
/// порядок добавления — иначе список «прыгал» бы между одинаковыми сетями.
void sort(NetworkList& list);

/// Уровень сигнала для индикатора: 1..4 (одна-четыре палочки).
/// 0 — сигнала нет, подключаться бессмысленно.
uint8_t signal_level(int rssi);

/// Годен ли пароль для защищённой сети.
///
/// WPA2 принимает либо парольную фразу 8..63 печатных ASCII, либо 64
/// шестнадцатеричных символа — «сырой» PSK. Проверяем именно это, а не
/// «непустая строка»: иначе на устройстве десять секунд висело бы
/// «подключение…», а потом приходил отказ, который пользователю ничего не
/// объясняет.
bool password_valid(const char* password);

/// Подпись защиты сети для экрана.
const char* security_name(bool secure);

}  // namespace wifi
