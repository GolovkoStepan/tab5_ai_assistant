#pragma once

// Веб-поиск RouterAI: поле `plugins` в запросе и источники в ответе.
//
// Разведка (Р-036) выяснила четыре вещи, которые определяют этот модуль:
//
//  1. Плагин `web` **работает вместе с tools** — отдельного запроса ради
//     совместимости не нужно. Но искать по тексту любой реплики он заставляет
//     ВСЕГДА, даже когда интернет не нужен (Р-038 п. 5: на «17×23» плагин
//     отдал пять ссылок на калькуляторы). Поэтому в основном запросе плагина
//     нет: он уходит только в поисковый подзапрос по вызову инструмента
//     `web_search` (Р-040). Решает модель, а не сервер — и это в сто раз
//     дешевле на болтовне.
//
//  2. Источники приходят в `choices[0].delta.annotations` (в стриминге) и
//     `choices[0].message.annotations` (без стриминга) — массивом объектов
//     `{"type":"url_citation","url_citation":{"url","title","content",
//     "start_index","end_index"}}`. Полей `citations`/`sources`/`references`
//     в ответе нет.
//
//  3. Все источники приходят ОДНИМ чанком. Повторов не наблюдалось, но
//     это наблюдение, а не гарантия: дедупликация по URL дешевле, чем дубли
//     в ленте.
//
//  4. Число результатов — только `max_results` в корне объекта плагина.
//     Вложенный `options` сервер молча игнорирует (вместе с любым неизвестным
//     полем, даже неизвестным id плагина: отвечает 200). Поэтому собираем
//     ровно `{"id":"web","max_results":N}` и не даём «настроить домены» —
//     это была бы ложная настройка.
//
// Чистые функции без Arduino, поэтому проверяются на хосте: ошибиться в
// разборе JSON глазами невозможно.

#include <stddef.h>
#include <stdint.h>

namespace web {

/// Сколько источников держим в одном ответе.
///
/// Плагин по умолчанию отдаёт пять; настройки разрешают запросить до десяти
/// (`search_max_results` в `config.json`). Держим десять, чтобы «сколько
/// попросили, столько и показали»: при восьми запрос с `max_results=10`
/// молча терял два источника, и это выглядело как потеря данных.
constexpr size_t kMaxSources = 10;

/// Пределы полей. URL длиннее 300 символов в выдаче не встречается, но
/// редиректы и параметры бывают длинными; заголовок ограничен 96 байтами,
/// чтобы список ссылок влезал в экран без прокрутки.
constexpr size_t kMaxUrlLen = 320;
constexpr size_t kMaxTitleLen = 128;
/// Выжимка нужна только для показа «о чём страница»; полный `content` бывает
/// в килобайты, а нам хватает начала.
constexpr size_t kMaxSnippetLen = 160;

/// Один источник.
struct Source {
    char url[kMaxUrlLen]{};
    char title[kMaxTitleLen]{};
    char snippet[kMaxSnippetLen]{};
};

/// Что нужно знать собранному списку.
struct List {
    Source items[kMaxSources]{};
    size_t count{0};

    /// Сколько источников пришло, но не влезло или оказалось дублем. Для
    /// диагностики на плате; в интерфейсе не показывается.
    size_t dropped{0};

    void clear()
    {
        count = 0;
        dropped = 0;
    }
};

/// Источники из одного события SSE (или из полного ответа без стриминга).
///
/// Понимает обе формы: `choices[0].delta.annotations` и
/// `choices[0].message.annotations` — как `tools::Accumulator::feed`.
///
/// Дубли по URL отбрасываются: список накапливается между чанками, и если
/// плагин пришлёт тот же список дважды, пользователь не должен увидеть его
/// дважды.
///
/// @return число ДОБАВЛЕННЫХ источников (0, если в чанке их не было)
size_t feed(const char* json, size_t len, List& out);

/// Есть ли в ответе поле `plugins`/`annotations` вообще. Нужно, чтобы
/// отличить «поиск был, но ничего не нашёл» от «поиска не было».
bool mentions_annotations(const char* json, size_t len);

/// Дописать источники из другого списка, пропуская уже известные URL.
///
/// За один ход агента бывает несколько ответов (шаг с инструментом, потом
/// итоговый), и в каждом свои `annotations`. Показывать надо все, но без
/// повторов: второй ответ часто ссылается на те же страницы.
///
/// @return сколько добавлено
size_t append(List& dst, const List& src);

/// Собирает поле `plugins` для тела запроса.
///
/// Форма проверена живьём (Р-036): `[{"id":"web","max_results":N}]`.
/// `max_results` вне диапазона 1..kMaxSources поднимается/опускается до
/// границы: передавать 0 значило бы просить «ноль результатов», а сервер
/// такое молча заменит своим умолчанием.
///
/// @return длина без завершающего нуля; 0, если буфер мал
size_t build_plugins_json(uint8_t max_results, char* out, size_t out_len);

/// Адрес самого релевантного источника — для `source_url` во фронтматтере
/// документа. Берём первый: плагин отдаёт их в порядке релевантности, и это
/// то, на что модель опиралась в первую очередь.
///
/// @return nullptr, если источников нет
const char* primary_url(const List& list);

/// Какой размер буфера нужен `format_list` для полного списка.
///
/// Считается из констант модуля, чтобы предел числа источников и буфер не
/// разъезжались. Точный худший случай: строка — «\n10. » (6) + домен (до 63) +
/// « — » (5) + заголовок (до 127) = 200 байт, десять строк и заголовок —
/// 2021 байт. Округляем до 240 на строку, чтобы правка любого предела не
/// сделала буфер тесным молча.
constexpr size_t kMaxListText = 64 + kMaxSources * 240;

/// Подпись источника для чата: «mi.com — Как сбросить фильтр».
///
/// Домен без `www.` — в чате он читается легче, чем полный адрес, а полный
/// всё равно есть в `url`. Если заголовка нет, остаётся только домен.
///
/// @return длина без нуля; 0, если буфер мал или список пуст
size_t format_source(const Source& src, char* out, size_t out_len);

/// Весь список источников одним текстом для ленты чата.
///
/// Начинается с пустой строки и заголовка «Источники:», дальше нумерованные
/// пункты по строке. Дописывается в конец ответа, поэтому ведущая пустая
/// строка — часть формата, а не случайность.
///
/// Если буфер кончается, список обрывается на границе пункта с «…»: половина
/// строки читалась бы как «источники кончились» (Р-038).
///
/// @return длина без нуля; 0 — список пуст или буфер мал даже для заголовка
size_t format_list(const List& list, char* out, size_t out_len);

/// Домен из URL без схемы, `www.` и пути: «https://www.mi.com/ru/x» → «mi.com».
///
/// @return длина без нуля; 0, если URL пустой или без домена
size_t domain_of(const char* url, char* out, size_t out_len);

}  // namespace web
