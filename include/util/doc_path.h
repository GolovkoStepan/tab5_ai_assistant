#pragma once

// Пути документов: проверка того, что модель не выведет нас за пределы архива.
//
// Зачем отдельный модуль. Путь приходит от модели — то есть от текста, который
// мы не контролируем. `../../config.json` в аргументе `write_doc` означал бы
// запись в настройки, а `/sdcard/chats/...` — порчу разговоров. Ошибка здесь
// не «неудобство», а потеря данных, поэтому проверка вынесена в чистые функции
// и покрыта тестами на хосте: на плате такой дефект ищут по испорченным файлам.
//
// Правила (из docs/ARCHITECTURE.md §5.1):
//   - путь относительный, всегда внутри /notes;
//   - никаких `..`, `.` и абсолютных путей;
//   - слаги ASCII: латиница, цифры, дефис, подчёркивание; разделитель — `/`;
//   - расширение `.md` добавляется, если его нет;
//   - вложенность ограничена, чтобы не получить дерево на 40 уровней.

#include <stddef.h>
#include <stdint.h>

namespace paths {

/// Максимальная длина нормализованного пути с завершающим нулём.
/// 96 байт: «home/air-purifier-filter-reset.md» — 33, запас на глубокие темы.
constexpr size_t kMaxPathLen = 96;

/// Максимальная глубина вложенности папок. Три — это `home/kitchen/notes/x.md`:
/// больше в бытовом архиве не нужно, а очень глубокое дерево неудобно листать.
constexpr size_t kMaxDepth = 3;

/// Максимальная длина одного сегмента (имени файла или папки).
constexpr size_t kMaxSegmentLen = 48;

/// Результат проверки.
enum class Result : uint8_t {
    Ok,
    Empty,           ///< пустой путь
    TooLong,         ///< не влез в kMaxPathLen
    TooDeep,         ///< больше kMaxDepth папок
    SegmentTooLong,  ///< сегмент длиннее kMaxSegmentLen
    Absolute,        ///< начинается с '/'
    Traversal,       ///< содержит `..` — попытка выйти наружу
    DotSegment,      ///< содержит `.` как сегмент
    BadChar,         ///< символ вне разрешённого набора
    BadExtension,    ///< расширение не `.md`
    EmptySegment,    ///< `//` или сегмент из одних пробелов
};

/// Человекочитаемая причина отказа — её возвращаем модели текстом.
/// Модель по такому тексту исправляется (проверено живым прогоном, Р-025).
const char* error_text(Result r);

/// Проверить и нормализовать путь документа.
///
/// Нормализация: убирает ведущие `./`, приводит к нижнему регистру (FAT32
/// всё равно регистронезависим, а два файла `Doc.md` и `doc.md` — это один
/// файл, и путаница в ссылках нам не нужна), добавляет `.md`.
///
/// @param in       путь от модели
/// @param out      буфер для нормализованного пути
/// @param out_len  его размер (нужно не меньше kMaxPathLen)
/// @return Ok либо причина отказа; при отказе out не изменяется
Result normalize(const char* in, char* out, size_t out_len);

/// Проверить путь БЕЗ нормализации — для чтения.
///
/// Отличие от normalize: расширение не добавляется и регистр не меняется.
/// Читать надо ровно то, что просили: если модель ошиблась регистром, лучше
/// честно сказать «не найден», чем молча открыть другой файл. На FAT32 это
/// сработает, но так поведение одинаково с любой ФС и в тестах.
Result check(const char* in);

/// Превратить произвольный текст в ASCII-слаг для имени файла.
///
/// Нужно, когда модель не дала путь, а дала заголовок: «Сброс ошибки
/// очистителя» → `sbrос-oshibki` невозможно (кириллица), поэтому кириллица
/// транслитерируется. Функция не претендует на академичность — нужен
/// предсказуемый, читаемый ASCII.
///
/// @return false, если после чистки не осталось ни одного символа
bool slugify(const char* text, char* out, size_t out_len);

/// Имя папки документа: `home/kitchen/x.md` → `home/kitchen`.
/// Для корня возвращает пустую строку.
void folder_of(const char* path, char* out, size_t out_len);

/// Имя файла без папки и без `.md`: `home/x.md` → `x`.
void name_of(const char* path, char* out, size_t out_len);

}  // namespace paths
