#pragma once

// Обрезка истории перед отправкой модели.
//
// У модели контекст на миллион токенов, но платим мы за каждый входной токен, а
// RAM и терпение пользователя не бесконечны. Простое «выбросить самое старое»
// ломает разговор: сообщение `tool` без предшествующего вызова инструмента
// сервер отклонит с 400. Поэтому режем по правилам, а не по энтузиазму.
//
// Чистые функции: список сообщений приходит снаружи, вызовов сети и SD нет.

#include <stddef.h>

#include "util/api_json.h"

namespace history {

/// Одно сообщение истории в том виде, в котором оно лежит на SD и уходит в API.
///
/// Строки не копируются: владелец — вызывающий. ChatStore держит тред в одном
/// буфере PSRAM, а сюда передаёт указатели: лишние копии истории на 32 КБ не
/// нужны.
struct Message {
    api::Role role{api::Role::User};
    const char* content{nullptr};
    /// Длина content в байтах (без завершающего нуля).
    size_t content_len{0};
    const char* tool_call_id{nullptr};
    const char* name{nullptr};
};

/// Что осталось после обрезки.
struct TrimResult {
    /// Первое отправляемое сообщение. Всегда 0, если в истории есть системное:
    /// оно уходит первым в любом случае.
    size_t begin{0};
    /// Первое НЕотправляемое сообщение после конца. Всё, что за ним, отрезано
    /// справа: это осиротевшие результаты инструмента.
    size_t end{0};
    /// Сколько сообщений уходит (end - begin).
    size_t kept{0};
    /// Сколько сообщений середины отброшено по бюджету.
    size_t dropped{0};
    /// Сколько байт контента уходит.
    size_t bytes{0};
    /// Системное сообщение сохранено.
    bool kept_system{false};
};

/// Оставляет допустимый правилами хвост истории, укладывающийся в бюджет.
///
/// Правила:
///   1. Системное сообщение (первое, `role == System`) уходит всегда и в
///      бюджет не входит: без него модель ведёт себя иначе, и это выглядит
///      для пользователя как «ассистент сломался».
///   2. Режем по бюджету с начала: свежие сообщения важнее старых.
///   3. История не начинается с `tool` — такой запрос сервер отклонит.
///   4. Последний вопрос пользователя остаётся, даже если он один больше
///      бюджета: пустой запрос бессмыслен.
///
/// @param msgs   сообщения в хронологическом порядке
/// @param count  их количество
/// @param budget бюджет контента в байтах (системное сообщение не считается)
/// @return границы отправляемого куска и статистика
TrimResult trim(const Message* msgs, size_t count, size_t budget);

/// Сколько байт занимает контент сообщений [from, count).
size_t total_bytes(const Message* msgs, size_t count, size_t from = 0);

}  // namespace history
