#pragma once

// Что показывает системный трей в правом верхнем углу: подписи и уровни.
//
// Зачем это отдельный модуль, а не код в экране. Правил здесь больше, чем
// кажется, и каждое легко испортить незаметно:
//
//   * процент заряда достоверен ТОЛЬКО на разряде. На Tab5 `getBatteryLevel()`
//     считает его по напряжению на ячейку (`Ina226.getBusVoltage() * 500`), а
//     зарядник держит на клеммах 8.4 В — то есть 4.2 В на ячейку, верхнюю
//     границу формулы. Поэтому сразу после подключения кабеля процент
//     скачком становится 100 % независимо от реального заряда. Показывать его
//     в этот момент — врать;
//   * на пустом отсеке та же формула тоже даёт 100 %: аппаратного признака
//     «есть ли аккумулятор» у Tab5 нет (docs/DECISIONS.md Р-016);
//   * у Wi-Fi «нет связи» не должно выглядеть как «есть»: пустое место на
//     месте значка читается как «экран сломался».
//
// Модуль чистый: ни Arduino, ни M5GFX. Рисование — в ui/tray.cpp, здесь только
// данные. Так правила проверяются на хосте.
//
// Адреса Wi-Fi в трее нет намеренно: он занимал сто с лишним пикселей, а на
// экране Wi-Fi всё равно показан подробнее — с именем сети. Значок отвечает на
// вопрос «связь есть?», на который адрес не отвечает.

#include <stddef.h>
#include <stdint.h>

namespace tray {

/// Что известно о заряде. Отдельно от `charging`/`discharging`, потому что в
/// `idle` M5Unified смешивает два разных случая (см. ниже).
enum class Charge : uint8_t {
    /// Ни заряда, ни разряда: аккумулятора нет ЛИБО он заряжен, и различить
    /// это на Tab5 нельзя — ни напряжения, ни аппаратного признака наличия.
    Unknown,
    /// Ток течёт в аккумулятор: заряд идёт.
    Charging,
    /// Заряд шёл в этой сессии и ток упал до нуля: аккумулятор заряжен.
    ///
    /// Это вывод из истории, а не измерение. M5Unified для Tab5 определяет
    /// состояние только по току INA226 и, когда заряд закончен, отдаёт `idle` —
    /// тот же код, что и при пустом отсеке. Поэтому «заряжено» можно объявить
    /// лишь потому, что мы сами видели, как заряд шёл. Без этой памяти
    /// «заряжается» и «уже заряжен» выглядели бы одинаково.
    Charged,
    /// Работаем от аккумулятора.
    Discharging,
};

/// Максимальная ширина подписи часов в трее: «Ср, 27 сент. 13:59» — худший
/// случай (двузначный день, длинное сокращение месяца). По ней трей отводит
/// слот, чтобы значок Wi-Fi не съезжал при смене месяца.
constexpr size_t kClockTextLen = 32;

/// Состояние для отрисовки. Собирается в main раз в секунду: INA226 и
/// WiFi.RSSI() читаются по шине/драйверу, а кадров около сотни в секунду.
struct Info {
    bool wifi_connected{false};
    bool wifi_connecting{false};
    /// Уровень сигнала 0..4 (0 — связи нет). Считается из RSSI.
    uint8_t wifi_level{0};
    /// Что писать рядом со значком: только «нет» или «…». При связи — пусто:
    /// значок уже всё сказал, а адрес на экране Wi-Fi.
    char wifi_text[8]{};

    /// Что известно о заряде.
    Charge charge{Charge::Unknown};
    /// Процент достоверен: аккумулятор разряжается и ток известен.
    bool battery_known{false};
    /// Заряд в процентах; -1 — неизвестен.
    int battery_percent{-1};
    /// Что писать рядом со значком: «87 %», «заряд», «заряжено» или «8.37 В».
    char battery_text[20]{};

    /// Дата и время для правого края: «Пт, 27 нояб. 13:59». Пусто, пока время
    /// не выставлено (RTC без заряда и NTP ещё не ответил) — выдуманное
    /// «01 янв. 00:00» выглядело бы как сбой часов.
    char clock_text[kClockTextLen]{};

    bool operator==(const Info& o) const;
    bool operator!=(const Info& o) const { return !(*this == o); }
};

/// Подпись Wi-Fi.
///
/// При связи подпись пустая: значок с заполненными палочками сам отвечает на
/// вопрос «связь есть?». Адрес живёт на экране Wi-Fi, где он нужен вместе с
/// именем сети, — в трее он дублировал его и отнимал место.
void wifi_label(bool connected, bool connecting, char* out, size_t out_len);

/// Подпись батареи.
///
/// @param percent_known процент достоверен (только на разряде)
///
/// Напряжение сюда намеренно не передаётся: при пустом отсеке INA226 видит
/// холостой ход зарядного узла, который периодически поднимается и гаснет
/// (8.37 ↔ 4.35 В на живой плате), и подпись мигала бы. В этом состоянии
/// выводится прочерк — «нет данных» честнее числа, которое ничего не значит.
void battery_label(Charge charge, bool percent_known, int percent, char* out, size_t out_len);

/// Уточнить состояние заряда с учётом истории сессии.
///
/// На Tab5 M5Unified различает только «ток внутрь», «ток наружу» и «тока нет».
/// «Тока нет» — это одновременно «аккумулятор заряжен» и «аккумулятора нет»,
/// и различить их измерением нельзя (Р-016). Единственное, что помогает, —
/// память: если заряд в этой сессии уже шёл, то «тока нет» означает, что он
/// закончился.
///
/// @param previous что было в прошлую секунду
/// @param charging сырое состояние: ток идёт в аккумулятор
/// @param discharging сырое состояние: ток идёт из аккумулятора
/// @param absent   известно, что аккумулятора нет (см. next_presence)
Charge next_charge(Charge previous, bool charging, bool discharging, bool absent);

/// Напряжение, ниже которого 2S-аккумулятор физически не может находиться.
///
/// Упаковка из двух Li-Po ячеек при работе не опускается ниже ~3.0 В на ячейку
/// (6.0 В на всю): защита отсекает раньше. Поэтому 5.5 В — заведомо недостижимое
/// для живой батареи значение. А вот холостой ход зарядного узла IP2326 в пустом
/// отсеке как раз там и оказывается: на живой плате он «дышит» между 4.34 и
/// 8.37 В с периодами 5–15 секунд.
constexpr int kPackMinPlausibleMv = 5500;

/// Что известно о наличии аккумулятора.
struct Presence {
    /// Аккумулятора нет (или доказательств его наличия не осталось).
    bool absent{false};

    bool operator==(const Presence& o) const { return absent == o.absent; }
};

/// Уточнить, есть ли аккумулятор.
///
/// Единственное прямое доказательство наличия — ток: он течёт только через
/// батарею. Поэтому появление тока сразу снимает подозрение.
///
/// Обратное доказательство даёт напряжение: если оно опустилось ниже
/// `kPackMinPlausibleMv`, аккумулятора нет — такую величину может дать только
/// холостой ход зарядного узла. Это подозрение **защёлкивается** и не снимается
/// само: иначе при пустом отсеке значок мигал бы между «заряжено» (высокая
/// фаза «дыхания», 8.37 В — правдоподобное напряжение) и «нет данных» (низкая
/// фаза, 4.34 В).
///
/// Именно из-за отсутствия этой защёлки владелец видел «заряжено» после того,
/// как снял аккумулятор при подключённом кабеле: заряд перед этим шёл, ток упал
/// до нуля, и история честно объявила заряд завершённым — хотя батареи уже не
/// было.
///
/// @param previous что было в прошлую секунду
/// @param current_flows сейчас течёт ток (заряд или разряд)
/// @param millivolts напряжение; <= 0 — чтение не удалось, ничего не доказывает
Presence next_presence(Presence previous, bool current_flows, int millivolts);

/// Уровень сигнала 1..4 для значка; 0 — палочки не рисуем.
///
/// Отдельно от wifi::signal_level, потому что здесь важен ещё и факт связи:
/// RSSI == 0 драйвер отдаёт, когда не подключён, и по таблице порогов это
/// выглядело бы как «отличный сигнал».
uint8_t wifi_level(bool connected, int rssi);

/// Дата и время для правого края трея: «Пт, 27 нояб. 13:59».
///
/// Формат намеренно короткий: трей делит полосу с названием экрана, и каждое
/// лишнее слово отнимает место у него. День недели и месяц — русские
/// сокращения, а не числа: «27.11.2026» человек читает медленнее, чем
/// «Пт, 27 нояб.», а год в трее не нужен вовсе.
///
/// Чистая функция без time(): часы читает вызывающий и передаёт разложенные
/// поля. Так формат проверяется на хосте, без платы и без NTP.
///
/// @param weekday 0 — воскресенье, как в struct tm
/// @param month   1..12
/// @param out     буфер; пустая строка, если поля вне диапазонов или буфер мал
/// @param out_len размер буфера, не меньше 24
/// @return false, если строка не поместилась или поля неверны
bool clock_label(int weekday, int day, int month, int hour, int minute, char* out, size_t out_len);

/// Пора предупреждать о разряде (заряд ниже порога из led_state).
bool battery_low(bool known, int percent);

/// Заполнение значка батареи, 0..100. -1 — неизвестно, рисуется пустой корпус.
///
/// @param charge «заряжено» даёт 100 даже без процента: это верхняя граница по
///               определению, а пустой корпус рядом с таким словом читался бы
///               как «ноль»
int battery_fill(Charge charge, bool known, int percent);

}  // namespace tray
