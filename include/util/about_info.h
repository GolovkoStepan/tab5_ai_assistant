#pragma once

// Сведения для экрана «О программе» и их форматирование.
//
// Зачем отдельный модуль. Экран About показывает то, что не видно больше нигде:
// версию, модель, адрес API, таймзону, свободную память и время работы. Почти
// всё это — готовые числа, которые main просто передаёт. Чистым остаётся одно:
// время работы, и именно его легко испортить незаметно:
//
//   * «0 мин» на свежей загрузке выглядит как ошибка, а не как «только что
//     включили»;
//   * «193 мин» человек пересчитывает в голове, а «3 ч 13 мин» читает сразу;
//   * на переполнении uint32 (49 суток) счёт не должен превращаться в мусор.
//
// Модуль чистый: ни Arduino, ни M5GFX. Числа берёт main.

#include <stddef.h>
#include <stdint.h>

namespace about {

/// Время работы в человекочитаемом виде.
///
/// @param ms     миллисекунды с загрузки
/// @param out    буфер для результата
/// @param out_len размер буфера, рекомендуется не меньше 24
///
/// Примеры: «только что» (меньше минуты), «7 мин», «3 ч 13 мин», «2 сут 4 ч».
/// Секунды не показываются: на экране, который открывают раз в месяц, они
/// менялись бы быстрее, чем человек успевает прочитать строку.
void uptime_label(uint32_t ms, char* out, size_t out_len);

}  // namespace about
