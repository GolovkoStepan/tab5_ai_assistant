#pragma once

// Какие сообщения ленты надо перемерить перед отрисовкой.
//
// Лента рисуется из кэша «сколько строк занимает каждое сообщение». Считать его
// заново на каждый кадр нельзя: тред на двести сообщений — это сотни вызовов
// переноса по словам, а кадры идут на каждом куске стриминга. Поэтому кэш
// инкрементальный, и вопрос «с какого сообщения считать» превратился в
// отдельную задачу — достаточно тонкую, чтобы ошибиться незаметно.
//
// Ошибка здесь стоит дорого и выглядит как два разных бага: заниженное число
// строк делает total_lines меньше высоты экрана, и тогда (1) прокрутка считает,
// что прокручивать нечего, и стрелки не двигают ленту, а (2) видимое окно
// обрывает ответ, потому что не знает, что он длиннее экрана.

#include <stddef.h>

namespace chatmeasure {

/// С какого сообщения пересчитывать строки.
///
/// @param measured_count    сколько сообщений уже измерено
/// @param count             сколько сообщений в треде сейчас
/// @param last_len          длина текста последнего сообщения
/// @param measured_last_len длина последнего сообщения на момент замера
/// @return индекс первого сообщения, которое надо перемерить; == count, если
///         перемерять нечего
///
/// Правила:
///  * тред стал короче — кэш неверен целиком, считаем с нуля;
///  * появились новые сообщения — считаем их;
///  * всё измерено, но последнее сообщение изменилось — перемеряем только его.
///
/// Последнее правило и есть исправление бага: раньше пересчёт последнего
/// сообщения был привязан к режиму экрана («идёт ответ»), а не к данным. Если
/// ответ приходил целиком за один tick() — быстрая модель, медленная отрисовка,
/// — к первому кадру экран уже снова Idle, и ответ оставался неизмеренным:
/// 5 КБ текста считались за две строки.
inline size_t first_to_measure(size_t measured_count, size_t count, size_t last_len, size_t measured_last_len)
{
    if (measured_count > count) return 0;
    if (measured_count < count) return measured_count;
    if (count > 0 && last_len != measured_last_len) return count - 1;
    return count;
}

}  // namespace chatmeasure
