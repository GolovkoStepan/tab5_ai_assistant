#pragma once

// Команды, приходящие по Serial.
//
// Зачем: вопрос в чат на плате набирается клавиатурой A164 или тапом, то есть
// руками. Для приёмки и для проверок «а что будет, если спросить вот так»
// нужен способ подать текст с компьютера — иначе каждый прогон требует
// человека у устройства, а повторять его через скрипт нельзя.
//
// Здесь только разбор строки: что именно делать с командой, решает main, у
// которого под рукой экраны. Чистая функция — значит проверяется на хосте.
//
// Формат намеренно явный: голый текст вопросом НЕ считается. Serial — это ещё
// и лог прошивки, и случайно отправленная строка не должна улетать в модель
// (это стоит денег и пишется в тред).

#include <stddef.h>
#include <stdint.h>

namespace serialcmd {

/// Экран, который можно открыть командой `screen <имя>`.
///
/// Отдельный перечень, а не `Screen` из `main.cpp`: разбор строки — чистая
/// функция, и тащить в неё перечисление прошивки значило бы сделать её
/// непроверяемой на хосте. Соответствие «здесь» ↔ «в main» — один `switch`.
enum class Screen : uint8_t {
    None,      ///< имя не распознано
    Chat,      ///< `screen chat`
    Threads,   ///< `screen threads` — список тредов
    Notes,     ///< `screen notes` — архив документов
    Wifi,      ///< `screen wifi`
    Api,       ///< `screen api` — настройки API
    Help,      ///< `screen help` — меню и справка
    Diag,      ///< `screen diag` — диагностика клавиатуры
    About,     ///< `screen about` — «О программе»
    Settings,  ///< `screen settings` — параметры устройства
};

/// Что делать с пришедшей строкой.
enum class Kind : uint8_t {
    None,        ///< пустая строка — молча пропустить
    Ask,         ///< вопрос в чат, текст в out_text/out_len
    Help,        ///< «help» или «?» — напечатать подсказку
    Thread,      ///< «thread» — распечатать открытый тред (диагностика, бесплатно)
    WifiOff,     ///< «wifi off» — выключить радио (проверка поведения без сети)
    WifiOn,      ///< «wifi on» — включить радио и подключиться по сохранённым данным
    Api,         ///< «api <адрес>» — подменить адрес API, текст в out_text/out_len
    Tz,          ///< «tz <зона>» — сменить таймзону, текст в out_text/out_len
    NewThread,   ///< «new» — начать новый тред (то же, что Ctrl+N)
    SaveAnswer,  ///< «save» — сохранить последний ответ в архив (то же, что Ctrl+S)
    DevStep,     ///< «dev <шаг>» — шаг параметра на экране параметров (то же, что ← →)
    Screen,      ///< «screen <имя>» — открыть экран, имя в out_text/out_len
    Unknown,     ///< строка есть, но это не команда — сказать об этом
};

/// Разобрать строку из Serial.
///
/// Понимает:
///   `ask <текст>`  — вопрос в чат (регистр «ask» любой)
///   `> <текст>`    — то же самое, короткая форма
///   `help`, `?`    — подсказка
///   `thread`       — распечатать открытый тред (диагностика, бесплатно)
///   `wifi off`     — выключить радио: проверка «что будет без интернета»
///   `wifi on`      — включить радио и подключиться к сохранённой сети
///   `api <адрес>`  — подменить адрес API (проверка на фальшивом сервере)
///   `tz <зона>`    — сменить таймзону, формат POSIX: `tz YEKT-5`
///   `new`         — начать новый тред (то же, что Ctrl+N)
///   `save`        — сохранить последний ответ в архив (то же, что Ctrl+S)
///   `dev <шаг>`   — шаг на экране параметров: `bright+1`, `timeout-1`,
///                    `layout`, `warn+1`, `crit-1`, `shut+1`, `tz+1` — эквивалент
///                    стрелок, чтобы проверять экран скриптом
///   `screen <имя>` — открыть экран: `chat`, `threads`, `notes`, `wifi`,
///                    `api`, `help`, `diag`, `about`, `settings`
///
/// Пробелы в начале и конце строки не считаются частью команды. Пробелы внутри
/// вопроса сохраняются как есть: «ask  2 + 2» спросит «2 + 2», а не «2 + 2»
/// без отступов — модель видит ровно то, что написал человек.
///
/// @param line      строка без завершающего перевода строки
/// @param len       её длина (может быть 0)
/// @param out_text  начало вопроса внутри line (указатель в буфер вызывающего)
/// @param out_len   длина вопроса
/// @return что делать; для Kind::Ask в out_text/out_len лежит текст
Kind parse(const char* line, size_t len, const char** out_text, size_t* out_len);

/// Разобрать имя экрана из `screen <имя>`.
///
/// @param name  имя, уже выделенное parse()
/// @param len   его длина
/// @return экран или `Screen::None`, если имя незнакомое
Screen parse_screen(const char* name, size_t len);

/// Подсказка по командам — одна строка, чтобы не засорять лог.
const char* help_text();

}  // namespace serialcmd
