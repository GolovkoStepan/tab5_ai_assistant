#pragma once

// История введённых вопросов: Alt+↑ / Alt+↓ в поле ввода чата.
//
// Зачем это нужно. Вопрос набирается на 70 клавишах, и повторить его иначе
// можно только заново: в ленте сообщение уже отправлено и не редактируется, а
// стрелки вверх-вниз листают ленту. Набрать «как сбросить ошибку у очистителя»
// второй раз — это минута работы вместо секунды.
//
// Модуль чистый: ни Arduino, ни M5GFX, ни выделения памяти. Арена приходит
// снаружи (в прошивке — из PSRAM), поэтому одна и та же логика проверяется на
// хосте и не зависит от кучи.
//
// Что решено и почему:
//
//   * **Черновик сохраняется.** Начал набирать «как сбро», нажал Alt+↑ — увидел
//     старый вопрос; Alt+↓ возвращает недописанное. Так же ведёт себя bash, и без
//     этого случайное нажатие Alt+↑ съедало бы набранное, а отменить это на
//     клавиатуре без мыши нечем.
//   * **Правка при листании не запоминается.** Если изменить вытащенный из
//     истории вопрос и нажать Alt+↑ ещё раз, правка пропадает — как в bash.
//     Иначе история превратилась бы в черновики, и «повторить вчерашний вопрос»
//     стало бы непредсказуемым.
//   * **Повторы склеиваются с соседом.** Спросить одно и то же дважды подряд
//     бывает, но в истории это одна запись: иначе двадцать слотов занимал бы
//     один вопрос.
//   * **Длинный текст не обрезается молча.** Если вопрос не влез в слот,
//     add() отказывает: вытащенный обрезанный вопрос ушёл бы в модель
//     покалеченным, и человек не понял бы, почему ответ не тот. Отказ виден
//     вызывающему, и он решает, что сказать.
//   * **История живёт в RAM.** Тред и так лежит на SD, а поиск по вчерашним
//     вопросам — отдельная задача. После перезагрузки история пуста, и это
//     ожидаемо: она про текущий разговор, а не про архив.

#include <stddef.h>
#include <stdint.h>

namespace inputhist {

/// Сколько вопросов помним. Двадцать — это вечер разговора; больше не влезает
/// в экран списка, если когда-нибудь понадобится его показать.
constexpr size_t kMaxEntries = 20;

/// Предел одного вопроса в байтах, включая завершающий ноль.
///
/// Совпадает с буфером поля ввода (`ChatScreen::kInputCap`): всё, что человек
/// может набрать, история обязана помнить целиком. Равенство закреплено
/// static_assert в `ui/chat_screen.cpp` — разъедутся, и длинный вопрос начнёт
/// молча не запоминаться.
constexpr size_t kEntryCap = 2048;

/// Сколько байт нужно арене: записи плюс один слот под черновик.
constexpr size_t kArenaBytes = (kMaxEntries + 1) * kEntryCap;

/// Состояние истории. Все байты текста — в арене, здесь только индексы.
struct History {
    /// Память под записи и черновик. Владелец — вызывающий.
    char* arena{nullptr};
    /// Сколько записей сейчас есть (0..kMaxEntries).
    uint8_t count{0};
    /// Индекс самой свежей записи в кольце.
    uint8_t head{0};
    /// 0 — поле показывает черновик, 1..count — записи от новых к старым.
    uint8_t cursor{0};
    /// Длина каждой записи в байтах, без завершающего нуля.
    size_t len[kMaxEntries]{};
    /// Длина сохранённого черновика.
    size_t draft_len{0};
    /// Черновик уже сохранён (иначе Alt+↓ вернул бы пустоту вместо набранного).
    bool draft_saved{false};
};

/// Привязать историю к памяти. Арена не обнуляется: содержимое всё равно
/// недоступно до первого add(), а обнулять 43 КБ в PSRAM на старте незачем.
///
/// @param arena      буфер не меньше kArenaBytes
/// @param arena_bytes его размер
/// @return false, если арены не хватает — тогда история не работает вовсе,
///         и вызывающий должен сказать об этом, а не молча терять вопросы
bool init(History& h, char* arena, size_t arena_bytes);

/// Забыть всё: и записи, и черновик. Вызывается при смене треда — история
/// относится к разговору, а не к устройству.
void clear(History& h);

/// Запомнить отправленный вопрос.
///
/// @param text вопрос как есть (UTF-8, без завершающего нуля в длине)
/// @param len  его длина в байтах
/// @return false, если вопрос пустой или не влез в слот (тогда он не
///         запомнится, но отправка от этого страдать не должна)
bool add(History& h, const char* text, size_t len);

/// Шаг вверх по истории: Alt+↑.
///
/// На первом шаге (когда поле показывает черновик) черновик сохраняется, чтобы
/// его можно было вернуть. Дальше — записи от новой к старой.
///
/// @param draft     что сейчас в поле ввода; используется только на первом шаге
/// @param draft_len его длина
/// @param out_len   [выход] длина возвращённого текста
/// @return текст для поля ввода либо nullptr, если истории нет или она уже
///         пролистана до конца (тогда поле менять не нужно)
const char* up(History& h, const char* draft, size_t draft_len, size_t* out_len);

/// Шаг вниз: Alt+↓. Возвращает черновик, когда записи кончились.
///
/// @param out_len [выход] длина возвращённого текста
/// @return текст для поля ввода либо nullptr, если поле уже показывает черновик
const char* down(History& h, size_t* out_len);

/// Поле показывает черновик (листание не начато или завершено).
bool at_draft(const History& h);

/// Вернуть листание к черновику, ничего не забывая.
///
/// Нужно там, где поле очищают не отправкой, а вручную (Esc, Del): записи
/// остаются, но следующее Alt+↑ должно начать с самой свежей, а не продолжать
/// с того места, где листание остановилось. Иначе поле пустое, а история
/// считает, что человек уже смотрит старый вопрос, и уводит ещё глубже.
void to_draft(History& h);

/// Сколько записей помним. Нужно подсказке «история 3 из 12».
size_t size(const History& h);

}  // namespace inputhist
