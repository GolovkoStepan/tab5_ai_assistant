#pragma once

// Поиск и разбор списка документов — без файловой системы.
//
// Здесь то, что легко проверить на хосте и легко испортить: как ищется
// подстрока с учётом регистра в кириллице, как обрезается сниппет, как из
// набора путей собирается ответ `list_docs`. Файловые операции — в hw/doc_store.
//
// Почему поиск свой, а не strcasestr: в кириллице верхний и нижний регистр —
// разные БАЙТЫ (А = D0 90, а = D0 B0), и посимвольное приведение к нижнему
// регистру в UTF-8 требует разбора многобайтных последовательностей. Ошибка
// здесь означала бы «поиск не находит фильтр», то есть главный сценарий
// использования архива.

#include <stddef.h>
#include <stdint.h>

namespace docsearch {

/// Найти подстроку без учёта регистра (латиница, кириллица).
///
/// @return указатель на первое вхождение в haystack или nullptr
const char* find_ci(const char* haystack, size_t hay_len, const char* needle, size_t needle_len);

/// Вырезать сниппет вокруг найденного места.
///
/// Сниппет — одна строка: переводы строк заменяются пробелами, потому что в
/// ответе модели многострочный кусок выглядел бы как рваная лента. Начало и
/// конец, если обрезано, помечаются «…».
///
/// @param text       текст, в котором нашли
/// @param text_len   его длина
/// @param hit        позиция совпадения
/// @param hit_len    длина совпадения
/// @param radius     сколько байт взять с каждой стороны
/// @param out        буфер результата
/// @param out_len    его размер
/// @return длина записанного (без завершающего нуля)
size_t snippet(const char* text, size_t text_len, size_t hit, size_t hit_len, size_t radius, char* out, size_t out_len);

/// Усечь текст по границе UTF-8, добавив «…», если что-то отброшено.
///
/// Резать многобайтный символ пополам нельзя: на экране появится ромбик с
/// вопросом, а модель получит в аргументах битый UTF-8.
///
/// @return длина записанного
size_t truncate_utf8(const char* text, size_t len, size_t max_bytes, char* out, size_t out_len);

/// Сколько байт занимает пробег UTF-8 символа, начинающегося с этого байта.
/// 5 и больше — битый байт, считаем его одним.
size_t utf8_char_len(unsigned char lead);

/// Строка результата `list_docs`: «путь — заголовок (дата)».
///
/// @param updated  дата в виде `ГГГГ-ММ-ДД` или пустая
/// @return длина записанного, 0 — не влезло
size_t format_list_row(const char* path, const char* title, const char* updated, char* out, size_t out_len);

}  // namespace docsearch
