#pragma once

// Веб-поиск как обычный инструмент агента (Р-040).
//
// Раньше плагин `web` уходил в КАЖДОМ первом запросе хода, и сервер искал по
// тексту последнего сообщения независимо от того, нужен ли интернет: на
// «привет» он тоже искал и брал за это ~2,1 ₽ (замерено, Р-038 п. 5 — на
// «17×23» плагин отдал пять ссылок на калькуляторы).
//
// Теперь поиск — инструмент: модель зовёт `web_search`, когда ей нужны внешние
// данные, а прошивка делает ОТДЕЛЬНЫЙ запрос с плагином и возвращает модели
// найденное. Плагина в основном запросе нет вовсе.
//
// Чистые функции без Arduino: сборка тела подзапроса и сборка результата
// проверяются на хосте. Сеть — в hw::ApiClient, решение «когда» — в экране.

#include <stddef.h>
#include <stdint.h>

#include "util/tool_registry.h"
#include "util/web_sources.h"

namespace wsearch {

/// Сколько источников просить у плагина, если модель не сказала иное.
///
/// Пять — умолчание самого плагина: проверено, что «без параметра» = 5.
constexpr uint8_t kDefaultResults = 5;

/// Какой длины аргумент `query` принимаем.
///
/// Длиннее — не поисковый запрос, а вставленный абзац: поисковик на такое
/// отвечает мусором, а платим мы за каждый запрос одинаково.
constexpr size_t kMaxQueryLen = 300;

/// Предел текста, который возвращаем модели как результат инструмента.
///
/// Меньше общего предела результата (tools::kMaxResultBytes = 4 КБ): результат
/// уходит в основную историю и остаётся там до конца треда, вытесняя диалог.
/// 2 КБ хватает на пересказ в тысячу символов и пять ссылок.
constexpr size_t kMaxResultBytes = 2048;

/// Схема инструмента `web_search` — как есть, в запрос к модели.
///
/// Описание по-русски и с примером: живые прогоны показали, что модель
/// исправляется по тексту описания, а не по формальной схеме (Р-025).
extern const char* const kToolSchema;

/// Тело запроса к /chat/completions для поиска.
///
/// Форма проверена живьём (Р-036, Р-038): `tools` НЕ передаём — иначе модель
/// внутри поискового запроса могла бы снова попросить инструмент, и получилась
/// бы рекурсия; `reasoning_effort: "none"` — рассуждения в поисковом подзапросе
/// не нужны, а стоят как выходные токены (в разведке до 4305 из 4787).
///
/// @param query         поисковый запрос (уже проверенный)
/// @param model         имя модели из настроек
/// @param max_results   сколько источников просить, 0 или больше предела — умолчание
/// @param out           буфер тела
/// @param out_len       его размер
/// @return длина без нуля; 0 — не влезло или аргументы пусты
size_t build_body(const char* query, const char* model, uint8_t max_results, char* out, size_t out_len);

/// Текст результата инструмента: найденный пересказ и источники.
///
/// Модели нужны и факты, и ссылки: текст она переработает в ответ, а ссылки
/// пойдут в `source_url` заметки. Если текста нет — остаются источники; если
/// нет и их — честное «ничего не нашлось», чтобы модель не выдумывала.
///
/// @param answer     текст ответа поискового подзапроса (может быть пустым)
/// @param answer_len его длина
/// @param list       найденные источники (nullptr — их нет)
/// @param out        буфер результата
/// @param out_len    его размер
/// @param list_from  с какого источника считать найденным ЭТИМ поиском
/// @return длина без нуля
///
/// `list` — указатель, а не ссылка: `web::List` весит ~6 КБ, и копия на стеке
/// задачи интерфейса роняла плату («Stack protection fault» на живой приёмке).
///
/// `list_from` нужен, потому что список источников на экране один на весь ход:
/// второй поиск в том же ходе нашёл бы «источники» от первого и отчитался бы
/// ими вместо честного «ничего не нашёл». В результат попадают только
/// источники, пришедшие после начала этого поиска.
size_t format_result(
    const char* answer, size_t answer_len, const web::List* list, char* out, size_t out_len, size_t list_from = 0);

/// Обработчик инструмента `web_search`.
///
/// В сеть не ходит: проверяет аргументы, складывает запрос в `ctx.search_query`
/// и взводит `ctx.needs_search`. Сеть — дело экрана: запрос занимает 20–30 с, а
/// обработчик синхронный, и вызывать его из обработчика потока нельзя.
///
/// @return всегда false — результат появится вторым вызовом, с готовым текстом
bool web_search_tool(const char* args, size_t args_len, tools::Context& ctx);

/// Зарегистрировать `web_search` в реестре.
bool register_tool(tools::Registry& reg);

}  // namespace wsearch
