#pragma once

// Баннер офлайн-режима в чате.
//
// Зачем отдельное правило. Без сети чат работает не «никак»: архив (Ctrl+O) и
// история тредов (Ctrl+T) целиком на SD, и открывать их можно. Пустой экран без
// объяснения читается как «устройство сломалось», а вечная надпись «нет сети» —
// как помеха, которую хочется убрать.
//
// Тонкость одна, и из-за неё это функция, а не строка в коде: во время
// ПОДКЛЮЧЕНИЯ сеть ещё не «нет» — она появляется. Показать «офлайн» в эти
// секунды значило бы соврать ровно там, где человек ждёт подключения.
//
// Модуль чистый: ни Arduino, ни M5GFX.

namespace offline {

/// Показывать ли баннер.
///
/// @param connected  сеть есть
/// @param connecting идёт автоподключение
/// @param has_message в полосе сообщений уже что-то есть (ошибка или
///                    подсказка). Тогда баннер не рисуется: две строки в
///                    одном месте спорили бы друг с другом
bool banner_visible(bool connected, bool connecting, bool has_message);

/// Текст баннера.
///
/// Говорит, что ДОСТУПНО, а не только чего нет: человеку нужно знать, что
/// делать дальше, а не констатировать проблему.
const char* banner_text();

}  // namespace offline
