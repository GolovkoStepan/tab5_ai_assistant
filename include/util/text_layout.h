#pragma once

// Раскладка текста на строки экрана и соответствие «каретка ↔ строка/столбец».
//
// Зачем отдельный модуль. Экран редактора рисует не строки файла, а строки
// СЕТКИ: перенос по ширине плюс явные переводы строки. Каретка живёт в байтах
// UTF-8, а стрелки вверх/вниз ходят по строкам сетки — и пересчёт между этими
// двумя системами координат делается на каждое нажатие. Ошибка здесь выглядит
// как «стрелка вниз прыгает на две строки» или «каретка уехала в конец файла»,
// и на плате её ищут, листая заметку руками. Поэтому арифметика вынесена в
// чистые функции и покрыта тестами.
//
// Строка сетки — это [начало, конец) в байтах; конец — либо '\n', либо место,
// где ширина в символах исчерпана. Сам '\n' в строку входит, но при отрисовке
// отбрасывается.

#include <stddef.h>
#include <stdint.h>

namespace textlayout {

/// Разложить текст на строки сетки.
///
/// @param text     UTF-8 текст
/// @param len      его длина в байтах
/// @param width    ширина строки в СИМВОЛАХ (не байтах)
/// @param offsets  массив начал строк; должен вмещать max_rows + 1 элементов
/// @param max_rows предел строк
/// @return число строк (>= 1 для пустого текста); offsets[0..count] заполнены,
///         offsets[count] — конец последней строки
size_t layout(const char* text, size_t len, size_t width, uint32_t* offsets, size_t max_rows);

/// Строка и столбец (в символах) для байтовой позиции каретки.
///
/// @param col_row [выход] номер строки
/// @param col_col [выход] столбец в символах, 0..width
void caret_row_col(const char* text, size_t len, size_t caret, size_t width, size_t* out_row, size_t* out_col);

/// Байтовая позиция для строки и столбца.
///
/// Если столбец больше длины строки, возвращается её конец: каретка не уходит
/// за текст.
size_t caret_pos(const char* text, size_t len, size_t row, size_t col, size_t width);

/// Перейти на строку вверх/вниз, сохранив столбец.
///
/// Столбец передаётся снаружи и НЕ сбрасывается при движении через короткие
/// строки: иначе каретка, пройдя через пустую строку, уже не вернулась бы на
/// прежнее место.
///
/// @param caret       текущая позиция
/// @param desired_col [вход/выход] желаемый столбец
/// @return новая позиция; == caret, если двигаться некуда
size_t move_vertical(const char* text, size_t len, size_t caret, size_t width, int delta, size_t& desired_col);

}  // namespace textlayout
