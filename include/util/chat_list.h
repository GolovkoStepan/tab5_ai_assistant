#pragma once

// Строка списка тредов: дата из имени файла и заголовок из первого вопроса.
//
// Экран тредов показывает десятки разговоров, и читать каждый тред целиком
// ради одной строки в списке нельзя: тред на 256 КБ при открытии списка
// означал бы прочитать с SD несколько мегабайт на каждый вход. Поэтому
// заголовок берётся из ПЕРВОЙ строки файла, а дата — прямо из имени
// (`chat-20261124-120000`), без чтения файла вообще.
//
// Правила разбора вынесены сюда, а не в экран: имя треда приходит из файловой
// системы, то есть может быть каким угодно. Ошибка здесь — падение или
// бессмысленная строка в списке, и ловить её тестами на хосте дешевле.
//
// Чистые функции без Arduino и SD.

#include <stddef.h>

namespace chatlist {

/// Дата и время создания треда из его имени.
struct Stamp {
    int year{0};
    int month{0};
    int day{0};
    int hour{0};
    int minute{0};
    int second{0};
    /// Имя содержит настоящую дату. false — часы были не выставлены, и в имени
    /// стоит `chat-00000000-…` с uptime вместо даты.
    bool real{false};
};

/// Разбирает имя треда вида `chat-20261124-120000` (и `chat-00000000-005946`).
///
/// Суффикс от повторного имени (`chat-20261124-120000-1`) допускается: два
/// треда можно создать в одну секунду.
///
/// @return false, если имя не в формате треда
bool parse_slug(const char* slug, Stamp& out);

/// Готовит дату для списка: «24.11 12:00» или «—» для треда без настоящего
/// времени (иначе в списке стояло бы «00.00 00:00», что выглядит как ошибка).
///
/// @return число байт без завершающего нуля, 0 если буфер мал
size_t format_stamp(const Stamp& stamp, char* out, size_t out_len);

/// Вытаскивает заголовок из первой строки файла треда.
///
/// Строка — JSONL сообщения (`util/chat_line`), но разбирать её полным парсером
/// незачем: нужен только `content` первого вопроса. Здесь — минимальный
/// поиск, устойчивый к любому мусору: если разобрать не удалось, возвращается
/// false, и экран покажет дату вместо заголовка.
///
/// Заголовок обрезается по границе UTF-8: разрезанная пополам кириллица дала
/// бы мусорный глиф, поэтому хвостовые байты продолжения отбрасываются.
///
/// @param line   первая строка файла (без перевода строки)
/// @param len    её длина
/// @param out    буфер заголовка
/// @param out_len его размер (не меньше 2)
/// @return false, если это не сообщение пользователя или текст пуст
bool title_from_line(const char* line, size_t len, char* out, size_t out_len);

}  // namespace chatlist
