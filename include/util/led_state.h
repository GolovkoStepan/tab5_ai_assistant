#pragma once

// Цвета двух светодиодов клавиатуры A164 по состоянию устройства.
//
// Зачем отдельная чистая функция: цвета — это правила («красный, если ошибка»),
// и именно в правилах легко ошибиться (одно состояние перекрывает другое,
// ошибка висит после успешного ответа). На хосте такие правила проверяются
// дешевле, чем на плате, где светодиод видно только глазами.
//
// Что означают светодиоды:
//   левый  — состояние модели: готов / отвечает / повтор / ошибка;
//   правый — питание: заряжается / от АКБ / садится / неизвестно.
//
// Разделение на два независимых измерения осознанное. Пытаться показать одним
// светодиодом и заряд, и сеть — значит гарантировать состояния, в которых
// правила спорят друг с другом (например «кабель воткнут, но заряжено»).
//
// --- Почему цвета не «полной яркости» ---------------------------------------
//
// Яркость в клавиатуре одна на оба светодиода (регистр 0x03, у нас 10 %), а
// глаз воспринимает разные оттенки очень по-разному: зелёный кажется в
// несколько раз ярче синего при одинаковом значении в регистре. Владелец так и
// спросил: «правый ярче горит, они точно в пол силы оба?» — регистр был
// одинаковый, а воспринимаемая яркость различалась в восемь раз.
//
// Поэтому цвета подобраны по **воспринимаемой** яркости (см. perceived()), а не
// по значению канала: внутри одного уровня оба светодиода светятся одинаково
// сильно. Уровней три:
//
//   тихо  (~15) — ничего не происходит: модель ждёт, питание в норме;
//   работа (~50) — идёт запрос, ответ или заряд: заметно, но не тревожно;
//   тревога (~95) — повтор, ошибка, батарея садится.
//
// Разница между уровнями — это и есть смысл индикации: тускло в покое, ярче
// когда есть на что посмотреть, ярче всего когда нужно вмешаться.
//
// Красный — исключение: чистый красный (255, 0, 0) физически не даёт больше
// 54 в этой метрике, а подмешивать зелёный ради «яркости» значит получить
// оранжевый. Ошибка остаётся чистым красным: цвет здесь важнее яркости.

#include <stdint.h>

namespace led {

/// Цвет одного светодиода. Значения 0..255, как в регистрах клавиатуры.
struct Rgb {
    uint8_t r{0};
    uint8_t g{0};
    uint8_t b{0};

    bool operator==(const Rgb& o) const { return r == o.r && g == o.g && b == o.b; }
    bool operator!=(const Rgb& o) const { return !(*this == o); }
};

/// Всё, что нужно знать, чтобы выбрать цвета.
///
/// Намеренно НЕ содержит «заряжен ли аккумулятор»: на Tab5 такого признака нет
/// (см. docs/DECISIONS.md Р-016), `idle` означает одновременно «заряжен» и
/// «аккумулятора нет». Поэтому правый светодиод в этом состоянии гаснет —
/// честное «ничего не могу сказать» лучше уверенного вранья.
struct Status {
    /// Идёт запрос к модели (ждём первого текста).
    bool busy{false};
    /// Уже идёт текст ответа.
    bool streaming{false};
    /// Ждём паузу перед повтором после 429/5xx.
    bool retrying{false};
    /// Последняя операция закончилась ошибкой, которую пользователь ещё видит.
    bool error{false};

    /// Идёт заряд (ток в аккумулятор).
    bool charging{false};
    /// Работаем от аккумулятора (ток из него).
    bool discharging{false};
    /// Заряд в процентах; -1 — неизвестен.
    int battery_level{-1};

    bool operator==(const Status& o) const;
    bool operator!=(const Status& o) const { return !(*this == o); }
};

/// Порог «садится»: ниже этого процента правый светодиод оранжевый.
constexpr int kLowBatteryPercent = 20;

// --- Воспринимаемая яркость -------------------------------------------------
//
// Рек. 709 (как в sRGB): линейная яркость каждого канала умножается на его
// вес в восприятии. Гамма-кривая 2.2 приближена квадратом — для подбора цвета
// этого достаточно, а точность закреплена тестами.
//
// Деления здесь нет намеренно. Первая версия считала `v*v/255` и делила итог —
// и на тусклых цветах (v ≈ 10) округление до нуля съедало всю разницу: метрика
// объявляла два явно разных цвета равными. Поэтому всё считается в целых с
// общим знаменателем, а потребитель вправе поделить сам.
//
// Функция constexpr: равенство яркостей внутри уровня закреплено static_assert
// ниже, то есть несогласованный цвет просто не соберётся.

/// Числитель метрики: 2126·r² + 7152·g² + 722·b² (знаменатель 2550000).
constexpr uint32_t perceived_num(const Rgb& c)
{
    return 2126u * c.r * c.r + 7152u * c.g * c.g + 722u * c.b * c.b;
}

/// Воспринимаемая яркость 0..255 — для тестов и для рассуждений в коде.
constexpr uint32_t perceived(const Rgb& c)
{
    return perceived_num(c) / 2550000u;
}

/// Насколько яркости двух цветов могут расходиться, оставаясь «одинаковыми».
///
/// Строгого равенства в целых числах не существует: 2126·r² + 7152·g² + 722·b²
/// редко даёт одно и то же двумя разными наборами. Требовать его — значит
/// получить палитру, где пары подобраны не по глазу, а по удаче делимости.
/// 0.1 % — заведомо ниже порога различия, но достаточно строго, чтобы
/// случайный цвет проверку не прошёл.
constexpr uint32_t kSameLevelTolerancePermille = 1;

/// Яркости неразличимы глазом (в пределах 0.1 %).
constexpr bool same_perceived(const Rgb& a, const Rgb& b)
{
    const uint32_t na = perceived_num(a);
    const uint32_t nb = perceived_num(b);
    const uint32_t diff = na > nb ? na - nb : nb - na;
    return diff * 1000u <= na * kSameLevelTolerancePermille;
}

// --- Готовые цвета ----------------------------------------------------------
//
// Значения подобраны по perceived(), а не «на глаз»: каждая пара одного уровня
// имеет одинаковую воспринимаемую яркость. Уровни: тихо ≈ 10, работа ≈ 51,
// тревога ≈ 94. «Работа» в пять раз ярче «тихо» — состояние читается, но
// светодиоды не слепят.

constexpr Rgb kOff{0, 0, 0};
/// Уровень «тихо»: готов, ждёт вопроса. Тот же уровень, что и нормальное
/// питание, — в покое оба светодиода светятся одинаково тускло.
constexpr Rgb kQuietBlue{0, 0, 236};  ///< N = 32266816
constexpr Rgb kQuietGreen{0, 75, 0};  ///< N = 32230000, расхождение 0.043 %
/// Уровень «работа»: запрос ушёл, идёт ответ, идёт заряд.
constexpr Rgb kWorkBlue{0, 108, 255};  ///< N = 130368978
constexpr Rgb kWorkGreen{0, 135, 0};   ///< N = 130345200, расхождение 0.018 %
/// Уровень «тревога»: повтор, батарея садится.
constexpr Rgb kAlarmOrange{255, 120, 0};  ///< perceived 94
constexpr Rgb kAlarmRed{255, 0, 0};       ///< perceived 54, максимум красного

static_assert(same_perceived(kQuietBlue, kQuietGreen), "в покое левый и правый светодиоды должны светиться одинаково");
static_assert(
    same_perceived(kWorkBlue, kWorkGreen), "во время работы левый и правый светодиоды должны светиться одинаково");
static_assert(perceived(kQuietGreen) < perceived(kWorkGreen), "«работа» должна быть ярче «тихо»");
static_assert(perceived(kWorkGreen) < perceived(kAlarmOrange), "«тревога» должна быть ярче «работы»");

// Имена цветов говорят об уровне яркости, а не об оттенке: по коду было
// неочевидно, что «тускло-синий» и «зелёный» — один и тот же случай «ничего
// не происходит», просто разной воспринимаемой яркости.

/// Цвета, которые надо записать в клавиатуру.
struct Colors {
    Rgb model;  ///< левый светодиод
    Rgb power;  ///< правый светодиод
};

/// Выбрать цвета по состоянию.
///
/// Приоритет у левого светодиода: повтор > ошибка > стриминг > ожидание
/// > готов. Повтор идёт ДО ошибки, потому что во время паузы ошибка уже
/// записана в поле сообщения, но пользователю важнее видеть, что клиент
/// работает, а не что он споткнулся.
Colors compute(const Status& s);

}  // namespace led
