#pragma once

// Цвета двух светодиодов клавиатуры A164 по состоянию устройства.
//
// Зачем отдельная чистая функция: цвета — это правила («красный, если ошибка»),
// и именно в правилах легко ошибиться (одно состояние перекрывает другое,
// ошибка висит после успешного ответа). На хосте такие правила проверяются
// дешевле, чем на плате, где светодиод видно только глазами.
//
// Что означают светодиоды:
//   левый  — состояние модели: готов / отвечает / повтор / ошибка;
//   правый — питание: заряжается / от АКБ / садится / неизвестно.
//
// Разделение на два независимых измерения осознанное. Пытаться показать одним
// светодиодом и заряд, и сеть — значит гарантировать состояния, в которых
// правила спорят друг с другом (например «кабель воткнут, но заряжено»).

#include <stdint.h>

namespace led {

/// Цвет одного светодиода. Значения 0..255, как в регистрах клавиатуры.
struct Rgb {
    uint8_t r{0};
    uint8_t g{0};
    uint8_t b{0};

    bool operator==(const Rgb& o) const { return r == o.r && g == o.g && b == o.b; }
    bool operator!=(const Rgb& o) const { return !(*this == o); }
};

/// Всё, что нужно знать, чтобы выбрать цвета.
///
/// Намеренно НЕ содержит «заряжен ли аккумулятор»: на Tab5 такого признака нет
/// (см. docs/DECISIONS.md Р-016), `idle` означает одновременно «заряжен» и
/// «аккумулятора нет». Поэтому правый светодиод в этом состоянии гаснет —
/// честное «ничего не могу сказать» лучше уверенного вранья.
struct Status {
    /// Идёт запрос к модели (ждём первого текста).
    bool busy{false};
    /// Уже идёт текст ответа.
    bool streaming{false};
    /// Ждём паузу перед повтором после 429/5xx.
    bool retrying{false};
    /// Последняя операция закончилась ошибкой, которую пользователь ещё видит.
    bool error{false};

    /// Идёт заряд (ток в аккумулятор).
    bool charging{false};
    /// Работаем от аккумулятора (ток из него).
    bool discharging{false};
    /// Заряд в процентах; -1 — неизвестен.
    int battery_level{-1};

    bool operator==(const Status& o) const;
    bool operator!=(const Status& o) const { return !(*this == o); }
};

/// Порог «садится»: ниже этого процента правый светодиод оранжевый.
constexpr int kLowBatteryPercent = 20;

/// Цвета, которые надо записать в клавиатуру.
struct Colors {
    Rgb model;  ///< левый светодиод
    Rgb power;  ///< правый светодиод
};

/// Выбрать цвета по состоянию.
///
/// Приоритет у левого светодиода: повтор > ошибка > стриминг > ожидание
/// > готов. Повтор идёт ДО ошибки, потому что во время паузы ошибка уже
/// записана в поле сообщения, но пользователю важнее видеть, что клиент
/// работает, а не что он споткнулся.
Colors compute(const Status& s);

// --- Готовые цвета ----------------------------------------------------------
//
// Значения приглушённые: глобальная яркость и так снижена, а полные 0xFF в
// тёмной комнате слепят. Держим их константами, чтобы «какой цвет задуман»
// было видно здесь, а не вычислялось умножением на яркость.

constexpr Rgb kOff{0, 0, 0};
constexpr Rgb kDimBlue{0, 12, 60};  ///< готов, ждёт вопроса
constexpr Rgb kGreen{0, 150, 20};   ///< отвечает / всё в порядке с питанием
constexpr Rgb kOrange{220, 70, 0};  ///< повтор / батарея садится
constexpr Rgb kRed{220, 0, 0};      ///< ошибка
constexpr Rgb kBlue{0, 40, 220};    ///< идёт заряд

}  // namespace led
