#pragma once

// Таймаут подсветки: когда гасить экран и когда просыпаться.
//
// Зачем отдельный модуль. Правил мало, но каждое легко испортить незаметно,
// а проверяется оно глазами и через минуты:
//
//   * гаснуть надо только тогда, когда человек ничего не делает — а «ничего не
//     делает» это не только «не нажимает клавиш»: идёт ответ модели, и человек
//     на него смотрит. Погасить экран посреди стриминга — значит спрятать ровно
//     то, что он ждал;
//   * нажатие любой клавиши и любой тап — активность. Некоторые события
//     приходят пачками (удержание клавиши), поэтому «проснулись» должно быть
//     отдельным ответом, а не «подсветка уже включена»;
//   * первое пробуждение тапом не должно считаться нажатием: иначе тап по
//     экрану в темноте нажал бы кнопку, которую человек не видит.
//
// Модуль чистый: ни Arduino, ни M5GFX. Управление подсветкой — в main.

#include <stdint.h>

namespace backlight {

/// Сколько миллисекунд бездействия до гашения.
///
/// 0 — не гасить вовсе (настройка `timeout_min = 0`).
uint32_t timeout_ms(uint8_t timeout_min);

/// Событие, случившееся в этом кадре.
struct Activity {
    /// Было ли нажатие клавиши.
    bool key{false};
    /// Был ли тап по экрану.
    bool touch{false};
    /// Идёт работа, которую человек ждёт: ответ модели, поиск, агентский ход.
    bool busy{false};
};

/// Что делать с подсветкой в этом кадре.
enum class Action : uint8_t {
    /// Ничего не менять.
    None,
    /// Погасить.
    Off,
    /// Зажечь обратно.
    On,
};

/// Решение по одному кадру.
///
/// @param was_on      подсветка горела в прошлом кадре
/// @param timed_out   бездействие дольше таймаута (считает вызывающий: у него
///                    millis() и настройки)
/// @param a           что случилось в этом кадре
/// @return On при пробуждении, Off при гашении, иначе None
///
/// Гашение не происходит, пока `busy`: экран с идущим ответом — не бездействие.
Action decide(bool was_on, bool timed_out, const Activity& a);

/// Значение яркости, которое надо записать в подсветку.
///
/// Отдельно от decide(), потому что яркость запоминается: гашение выставляет
/// 0, а пробуждение обязано вернуть прежнюю, а не значение по умолчанию.
///
/// @param normal  яркость из настроек (1..255)
/// @param on      подсветка должна гореть
uint8_t brightness(uint8_t normal, bool on);

}  // namespace backlight
