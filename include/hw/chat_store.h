#pragma once

// Треды чата на SD: чтение, дозапись, список, удаление.
//
// Формат — JSONL, одна строка на сообщение (docs/ARCHITECTURE.md, 5.2). Дозапись
// в конец, а не перезапись файла: при обрыве питания теряется максимум
// последняя строка, и тред остаётся читаемым. Полная перезапись на каждое
// сообщение означала бы, что обрыв питания губит весь разговор.
//
// Текст всех сообщений лежит в одной арене в PSRAM. Копировать его на каждый
// кадр нельзя: тред на 100 КБ при перерисовке 100 раз в секунду не оставит
// памяти под TLS. Сообщения лишь ссылаются на арену.
//
// Файловые операции — здесь; сборка и разбор строк — в util/chat_line, где они
// тестируются на хосте.

#include <stddef.h>
#include <stdint.h>

#include "util/api_json.h"
#include "util/chat_line.h"

namespace hw {

/// Одно сообщение треда. Текст указывает в арену ChatStore и живёт, пока
/// тред не перезагружен или не очищен.
struct ChatMessage {
    api::Role role{api::Role::User};
    const char* content{nullptr};
    size_t content_len{0};
    char ts[chatline::kMaxTs]{};
    long input_tokens{0};
    long output_tokens{0};
    bool partial{false};
    /// Для role == Tool: вызов, на который это сообщение отвечает.
    char tool_call_id[chatline::kToolCallIdLen]{};
    /// Для role == Tool: имя инструмента.
    char name[chatline::kToolNameLen]{};
    /// Для role == Assistant: массив вызовов как есть (указывает в арену).
    ///
    /// Хранится, даже если мы его уже выполнили: без этого сообщения сервер
    /// не понимает, на что отвечают последующие role=tool.
    const char* tool_calls{nullptr};
    size_t tool_calls_len{0};
};

class ChatStore {
public:
    /// Максимум сообщений в треде.
    static constexpr size_t kMaxMessages = 200;

    /// Размер арены под текст всех сообщений.
    static constexpr size_t kMaxArenaBytes = 160 * 1024;

    /// Максимальный размер файла треда, который читаем целиком.
    static constexpr size_t kMaxFileBytes = 256 * 1024;

    /// Максимальная длина одной строки файла.
    ///
    /// 40 КБ, а не 16: в строке сообщения ассистента лежит массив вызовов
    /// инструментов, а в аргументах write_doc — текст документа. Восемь
    /// вызовов по 4 КБ не влезли бы в 16 КБ, и строка не записалась бы —
    /// агент выглядел бы «сломавшимся» на ровном месте.
    static constexpr size_t kMaxLineBytes = 40 * 1024;

    /// Максимальная длина текста одного сообщения.
    static constexpr size_t kMaxContentBytes = 12 * 1024;

    /// Открыть каталог тредов, выделить память.
    /// @return false, если SD недоступна или не хватило памяти
    bool begin();

    /// Загрузить тред из файла.
    ///
    /// @param slug имя файла без пути и расширения (ASCII)
    /// @return false, если файла нет или он не прочитался
    bool load(const char* slug);

    /// Загрузить самый свежий тред: имя начинается с `chat-ГГГГММДД-…`,
    /// поэтому лексикографически наибольшее имя — самое новое.
    ///
    /// Нужно после перезагрузки: иначе пользователь после включения видел бы
    /// пустой экран, хотя треды на карте лежат. Список тредов появится
    /// отдельным экраном позже.
    ///
    /// @return false, если тредов нет или ни один не прочитался
    bool load_latest();

    /// Открыть пустой тред в памяти (файл появится при первом сообщении).
    void create(const char* slug);

    /// Начать новый тред с именем по времени.
    bool create_new(char* out_slug, size_t out_len);

    /// Добавить сообщение: сначала строка в файл, потом в память.
    ///
    /// Порядок важен: если запись не удалась, сообщение не должно попасть в
    /// ленту — иначе оно исчезнет после перезагрузки, и пользователь решит,
    /// что тред «теряет сообщения».
    /// @param tool_call_id для role == Tool: идентификатор вызова
    /// @param name         для role == Tool: имя инструмента
    /// @param tool_calls   для role == Assistant: массив вызовов как есть
    bool append(const api::Role& role, const char* content, const char* ts, long input_tokens, long output_tokens,
        char* err, size_t err_len, const char* tool_call_id = nullptr, const char* name = nullptr,
        const char* tool_calls = nullptr);

    /// Откатить последнее сообщение, если это вопрос пользователя без ответа.
    ///
    /// Нужно для отмены до первого слова: вопрос уже дописан в файл, но ответа
    /// на него не будет, и следующий ответ модели прилип бы к нему — в ленте
    /// получилось бы «Назови цвет» → «Пять шагов». Откат обрезает файл на
    /// длину последней записи и убирает сообщение из памяти.
    ///
    /// @return false, если откатывать нечего (тред пуст или последнее сообщение
    ///         не вопрос) или файл не удалось обрезать
    bool undo_last_user(char* err, size_t err_len);

    /// Начать ответ модели.
    ///
    /// Сообщение добавляется только в память и попадает в файл при
    /// flush_last(), когда ответ дописан. Записывать пустой ответ сразу
    /// нельзя: при обрыве питания в треде осталась бы пустая реплика модели,
    /// неотличимая от «модель ничего не сказала».
    bool begin_answer(char* err, size_t err_len);

    /// Дописать кусок к растущему ответу.
    ///
    /// Текст живёт в отдельном буфере треда и не перевыделяется: ответ приходит
    /// сотнями мелких кусков, и выделять память на каждый — верный способ
    /// получить фрагментацию кучи посреди разговора.
    ///
    /// @return false, если тред не открыт или ответ уже не помещается (тогда
    ///         кусок отброшен, а ответ помечается неполным)
    bool append_to_last(const char* text, size_t len);

    /// Приложить к последнему (растущему) сообщению массив вызовов инструментов.
    ///
    /// Нужно, когда модель вместо текста попросила инструменты: её сообщение с
    /// вызовами обязано попасть в файл и в следующий запрос, иначе сервер не
    /// свяжет ответы role=tool с вызовами.
    bool set_last_tool_calls(const char* json);

    /// Зафиксировать служебные поля последнего сообщения: время, счётчики,
    /// пометку неполного ответа.
    bool finish_last(const char* ts, long input_tokens, long output_tokens, bool partial);

    /// Дописать готовый ответ в файл треда.
    ///
    /// Именно дозапись одной строки, а не перезапись файла: перезапись делала
    /// историю заложником памяти (любое повреждение указателей уезжало на
    /// карту) и писала весь тред до 256 КБ после каждого ответа.
    ///
    /// Писать на каждый токен всё равно нельзя — SD этого не любит, поэтому
    /// вызов ровно один, когда ответ дописан.
    bool flush_last(char* err, size_t err_len);

    /// Текст последнего сообщения и его длина. Для экрана: рисовать ленту
    /// удобнее из одного места, чем из двух буферов.
    const ChatMessage* last() const { return _count > 0 ? &_messages[_count - 1] : nullptr; }

    /// Отменить последнее сообщение (ответ не удалось даже начать).
    void drop_last();

    size_t count() const { return _count; }
    const ChatMessage& at(size_t i) const { return _messages[i]; }

    /// Есть ли несохранённое изменение последнего сообщения.
    bool has_unsaved() const { return _unsaved_tail; }

    /// Имя текущего треда (пусто, если тред не открыт).
    const char* slug() const { return _slug; }

    /// Удалить тред с диска.
    bool remove(const char* slug);

    /// Очистить открытый тред: файл усекается до нуля, память сбрасывается,
    /// имя треда остаётся тем же.
    ///
    /// Именно усечение (`FILE_WRITE`, то есть "w"), а не удаление с созданием
    /// заново: если создание не удастся, на карте не осталось бы ни старого
    /// треда, ни нового, и разговор пропал бы молча. Усечение — одна операция:
    /// либо файл пуст, либо он не тронут.
    ///
    /// @return false, если тред не открыт или файл не удалось усечь (тогда
    ///         память не тронута, и на экране остаётся то же, что было)
    bool clear(char* err, size_t err_len);

    /// Заголовок треда: первое сообщение пользователя без переводов строк.
    bool title(char* out, size_t out_len) const;

    /// Одна строка списка тредов. Заполняется list_threads().
    ///
    /// Заголовок копируется строкой, а не указывает в арену: список живёт своей
    /// жизнью и переживает смену открытого треда.
    struct ThreadInfo {
        char slug[48]{};
        /// Дата и время создания.
        int year{0};
        int month{0};
        int day{0};
        int hour{0};
        int minute{0};
        /// Время настоящее (часы были выставлены).
        bool time_known{false};
        /// Первый вопрос пользователя. Пусто, если файл пуст или не разобрался.
        char title[96]{};
        /// Сколько байт занимает файл — по нему видно, пустой ли тред.
        size_t bytes{0};
    };

    /// Сколько тредов отдаёт list_threads() за раз.
    static constexpr size_t kMaxListedThreads = 40;

    /// Собрать список тредов с карты, от новых к старым.
    ///
    /// Читает только ПЕРВУЮ строку каждого файла (заголовок) — открывать тред
    /// целиком ради строки в списке значило бы прочитать с SD мегабайты на
    /// каждый вход в список.
    ///
    /// @param out      массив результатов
    /// @param cap      его размер (не больше kMaxListedThreads)
    /// @return сколько заполнено, 0 если тредов нет или SD недоступна
    size_t list_threads(ThreadInfo* out, size_t cap);

    /// Сколько байт занимает текст всех сообщений — для бюджета истории.
    size_t total_bytes() const;

    /// Проверить имя треда: только ASCII-буквы, цифры, дефис и подчёркивание.
    /// Путь собирается из имени, и «../config» здесь был бы записью вне каталога.
    static bool valid_slug(const char* slug);

private:
    bool read_file(const char* slug);
    void parse_buffer();

    /// Скопировать текст в арену и заполнить ChatMessage.
    bool store_message(const api::Role& role, const char* content, const char* ts, long input_tokens,
        long output_tokens, bool partial, ChatMessage& out, const char* tool_call_id = nullptr,
        const char* name = nullptr, const char* tool_calls = nullptr);

    /// Готовит строку JSONL сообщения. false — не поместилось.
    static bool build_line(const ChatMessage& msg, char* out, size_t out_len);

    static void make_path(const char* slug, char* out, size_t out_len);
    /// Арена под текст всех сообщений, кроме растущего ответа.
    char* _arena{nullptr};
    size_t _arena_used{0};

    /// Буфер растущего ответа. Отдельный и фиксированный: ответ дописывается
    /// по куску на каждое событие стриминга, и копить копии в арене значило бы
    /// исчерпать её на одном длинном ответе.
    char* _tail{nullptr};
    /// Сколько байт ответа уже записано в _tail.
    size_t _tail_used{0};

    /// Буфер файла: читаем тред целиком, разбираем, текст уезжает в арену.
    char* _file{nullptr};

    ChatMessage _messages[kMaxMessages]{};
    size_t _count{0};

    /// Буфер под массив вызовов инструментов при разборе строки. Один на
    /// весь разбор: текст копируется в арену сразу, поэтому живой он не
    /// остаётся. 8 КБ с запасом на несколько вызовов с аргументами.
    char* _calls_scratch{nullptr};
    static constexpr size_t kCallsScratchBytes = kMaxLineBytes;

    /// Буфер строки для записи. В PSRAM: 40 КБ статикой отнимали бы
    /// внутреннюю RAM, которая нужна TLS.
    char* _line{nullptr};

    char _slug[48]{};
    /// Последнее сообщение изменено в памяти, но ещё не записано в файл.
    bool _unsaved_tail{false};

    /// Сколько байт заняла последняя дозапись (строка + перевод) и сколько
    /// занимала арена до неё. По ним undo_last_user() откатывает и файл, и
    /// память, не перечитывая тред с карты.
    size_t _last_append_bytes{0};
    size_t _last_append_arena{0};
    size_t _last_append_msg_len{0};
    bool _ready{false};
};

}  // namespace hw
