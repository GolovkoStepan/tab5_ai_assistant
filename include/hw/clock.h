#pragma once

// Системные часы: таймзона из настроек и синхронизация по NTP.
//
// Зачем отдельный модуль. В прошивке есть три источника времени, и путать их
// легко:
//   * RTC (RX8130 на Tab5) — идёт от суперконденсатора. Пока он не зарядился
//     или не был выставлен, отдаёт мусор («2000-01--1»), и это нормально;
//   * системные часы ESP-IDF — сбрасываются в ноль при каждой перезагрузке;
//   * NTP — единственный источник настоящего времени, и он доступен только
//     при подключённом Wi-Fi.
//
// Порядок: при старте подхватываем время из RTC (если оно осмысленное), а
// когда поднимется сеть — один раз синхронизируемся по NTP и записываем
// результат обратно в RTC. Тогда треды получают правильные имена и метки,
// а после перезагрузки без сети время берётся из RTC.
//
// Почему не configTzTime при старте: SNTP стартует запросы сразу, а Wi-Fi на
// этой плате живёт на сопроцессоре C6 и поднимается секунды. Запросы в пустоту
// ничего не портят, но синхронизацию надо запускать тогда, когда сеть есть.

#include <stdint.h>
#include <time.h>

#include "util/settings.h"

namespace hw {

namespace clock_sync {

/// Самое раннее осмысленное время: 2020-01-01T00:00:00Z.
///
/// До этой отметки time() возвращает секунды с момента загрузки, а не время
/// суток. Без такой проверки треды назывались `chat-19700101-005946`, и это
/// выглядело как сломанные часы, а не как «время ещё не пришло».
constexpr time_t kMinValidEpoch = 1577836800;

/// Выставить таймзону и подхватить время из RTC.
///
/// Таймзона задаётся переменной TZ в формате POSIX («MSK-3»): тогда
/// localtime_r() даёт местное время, и его не надо пересчитывать вручную.
void begin(const settings::Config& cfg);

/// Продвинуть синхронизацию. Вызывать в цикле: она стартует NTP, когда
/// появляется сеть, и записывает полученное время в RTC.
///
/// @param wifi_connected есть ли сейчас сеть
void tick(bool wifi_connected);

/// Время уже осмысленное (пришло из RTC или от NTP)?
bool valid();

/// Время уже сверено с NTP в этом запуске?
bool synced();

/// Записать системное время в RTC. Вызывать после успешной синхронизации.
/// @return false, если RTC не отвечает (тогда просто живём на системных часах)
bool store_to_rtc();

}  // namespace clock_sync

}  // namespace hw
